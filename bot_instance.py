# ============================================================
# ЦЕНТРАЛЬНЫЕ ОБЪЕКТЫ БОТА — bot_instance.py
# ============================================================
# Здесь создаются главные объекты библиотеки maxo:
#
#   Bot        — «клиент» / точка входа в MAX Bot API. Умеет слать
#                сообщения, редактировать их, отвечать на колбэки и т.д.
#                Внутри него уже настроены авторизация, обработка ошибок
#                и привязка всех методов API (send_message, edit_message
#                и т.п. — это асинхронные методы Bot).
#
#   Dispatcher — «диспетчер»: корневой узел, который принимает все
#                апдейты от LONG POLLING и раздаёт их обработчикам.
#                В maxo Dispatcher — это Router (корень дерева роутеров).
#                Самое важное: Dispatcher ПО УМОЛЧАНИЮ подключает FSM
#                (MemoryStorage) и обогащение контекста, поэтому
#                обработчики автоматически получают параметр
#                fsm_context для работы с состояниями.
#
# Обработчики регистрируются в отдельных Router'ах (по одному роутеру
# на каждую подсистему: регистрация, меню, заметки и т.д.), а потом
# подключаются к Dispatcher в handlers/__init__.py через
# dp.include_router(...). Такой подход принято называть «деревом
# роутеров»: Dispatcher — корень, а модульные роутеры — ветки.
# ============================================================

from maxo import Bot, Dispatcher
from config import BOT_TOKEN

