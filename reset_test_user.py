# -*- coding: utf-8 -*-
"""
Сброс тестового аккаунта 115511930 в «нового пользователя»,
чтобы можно было заново пройти регистрацию в боте и проверить уведомление.

Аккаунт полностью удаляется из БД (SQLite): сам пользователь, его заметки,
логи ИИ и записи об ошибках. При следующем нажатии /start бот начнёт
регистрацию заново (как для совсем нового пользователя) и при этом
СОХРАНИТ chat_id, по которому придёт уведомление после подтверждения заявки
в панели модератора.

Запуск:
    python reset_test_user.py
"""
# --- Стандартная библиотека ---
import sys   # нужен для sys.path — добавления папки проекта в пути поиска
import os    # нужен для os.path — вычисления абсолютного пути к проекту

# Добавляем папку проекта в путь, чтобы заработал `import database`.
# __file__ — путь к этому скрипту; dirname+abspath даёт корень проекта
# независимо от того, из какой папки была запущена команда.
# Без этого python не нашёл бы модуль database.py при запуске из другой папки.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import database as db   # модуль БД (функции user_exists / delete_user)

# ВНИМАНИЕ про старое состояние регистрации:
# раньше `state_manager.clear_state(UID)` чистил in-memory "шаг регистрации"
# (соответствие user_id -> шаг). Теперь логику шагов регистрации ведёт
# maxo FSM (handlers/registration.py). При старте регистрации по /start
# handler сам очищает FSM, поэтому ручная очистка здесь не нужна —
# файл state_manager.py удалён вместе с переходом на maxo.

# ID тестового аккаунта (тот, что приходит от MAX как реальный user_id).
# Это ТОТ ЖЕ ID, который бот использует как первичный ключ в users.
UID = 115511930


def reset():
    # Шаг 1. Проверяем, есть ли такой пользователь в БД вообще.
    # Если пользователя уже нет в БД — удалять нечего: регистрация
    # начнётся с нуля при первом же /start.
    if not db.user_exists(UID):
        print(f"Пользователь {UID} уже отсутствует в БД — регистрация начнётся заново при /start.")
    else:
        # delete_user стирает строки из всех таблиц (users, notes, ai_log,
        # ai_errors) и возвращает их суммарное количество.
        print(f"Удаляю пользователя {UID} из БД...")
        removed = db.delete_user(UID)
        print(f"  удалено строк: {removed}")

    # Шаг 2. Печатаем подсказку, что делать дальше: /start в боте, затем
    # подтверждение в панели модератора — на сохранённый chat_id придёт
    # уведомление (chat_id бот записывает в users при первом контакте).
    print("")
    print("Теперь в боте нажми /start — начнётся регистрация заново.")
    print("Пройти регистрацию -> появишься во вкладке «Заявки на подтверждение».")
    print("Открой панель (python moderator_app.py), нажми «Подтвердить».")
    print("Бот отправит тебе уведомление на сохранённый chat_id.")


# Точка входа: сброс выполняется только при прямом запуске скрипта
# (python reset_test_user.py), а не при импорте одной функции сброса.
if __name__ == "__main__":
    reset()