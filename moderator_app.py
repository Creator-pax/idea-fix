    def _selected_pending_id(self):
        # user_id из выбранной строки таблицы «Заявки» (скрытая колонка).
        val = self.pending_table.selected_value()
        if val is None or val == "":
            return None   # строка не выбрана
        try:
            return int(val)
        except (TypeError, ValueError):
            return None   # мусор в скрытой колонке — считаем, что строки нет

    def _target_user_id(self):
        """user_id из поля ввода либо из выбранной строки таблицы пользователей."""
        manual = self.user_id_entry.get().strip()   # текст из поля «ID пользователя»
        if manual.isdigit():
            return int(manual)   # приоритет у ручного ввода ID
        val = self.users_table.selected_value()     # иначе берём выделенную строку
        if val is None or val == "":
            return None
        try:
            return int(val)
        except (TypeError, ValueError):
            return None

