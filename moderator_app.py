        # Показывает полный текст вопроса из выбранной строки логов ИИ.
        sel = self.ailogs_table.tree.selection()
        if not sel or not sel[0]:
            messagebox.showinfo("Вопрос", "Выбери строку в таблице логов.")
            return
        values = self.ailogs_table.tree.item(sel[0], "values")
        question = values[-2] if len(values) >= 2 else "—"   # предпоследняя = полный вопрос
        user_id = values[-1] if values else None             # скрытая колонка
        # Извлекаем полный вопрос из БД по совпадению времени+пользователя
        # (глядя в лог — там точный текст вопроса).
        logs = db.get_ai_logs(limit=500)
        match = None
        for log in logs:
            if str(log.get("user_id")) == str(user_id):
                match = log
                break
        if match:
            question = match.get("question") or question   # берём точный текст из БД
        # Открываем окно с полным текстом вопроса.
        DetailWindow(self, "❓ Полный вопрос", str(question), width=620, height=420)

