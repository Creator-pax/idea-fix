# --- Группы импортов ----------------------------------------------------
# Импорт осознанно разбит на три группы, чтобы было видно, кто от кого зависит:
#   1. Стандартная библиотека — файлы, время, потоки, формат CSV, sys.path;
#   2. Внешняя библиотека customtkinter — современный «skin» поверх tkinter;
#   3. Модули проекта — database (SQLite-запросы) и bot_instance (Telegram).
#
# Почему модули проекта в самом низу: database может настраивать sys.path для
# своих файлов, поэтому его подключение отложено, пока стандартные библиотеки
# уже загружены. Порядок внутри группы не важен, но логически сперва идёт
# data-слой (db), а от него уже отталкивается GUI.
#
# Дальше по тексту GUI-код НИКОГДА не обращается к SQLite напрямую — только
# через функции модуля db. Это изолирует панель от деталей схемы БД.

# tkinter и customtkinter: первый даёт базовые виджеты (диалоги сохранения,
# сообщения, стилизуемые таблицы ttk.Treeview), второй — красивые темизируемые
# кнопки/окна поверх того же Tcl/Tk. Импорты не взаимозаменяемы: filedialog,
# messagebox, ttk остаются именно из tkinter, их аналогов в ctk нет.
import customtkinter as ctk   # обёртка над tkinter с современным видом

import database as db            # все запросы к БД
from bot_instance import bot     # бот-инстанс: отправка уведомлений/рассылок

# Модуль database (db) — единственный «мост» к SQLite: любой запрос, от чтения
# профиля до каскадного удаления, идёт через его функции. Благодаря этому:
#   • панель не знает схемы БД — слой данных можно менять без правки GUI;
#   • те же запросы использует и сам бот — функционал общий на двоих;
#   • подключение и транзакции живут в одном месте, а не дублируются.
#
# bot_instance отдаёт готовый объект бота (aiogram-совместимый). Панель лишь
# вызывает bot.send_message в асинхронном стиле: через asyncio.run() по одному
# сообщению на действие. Это единственное место взаимодействия GUI с Telegram.

# Примечание по архитектуре: панель НЕ работает напрямую с Telegram — за отправку
# сообщений отвечает единый экземпляр бота (bot_instance), а запросы к SQLite
# инкапсулированы в модуль database (db). GUI-код в этом файле только вызывает
# готовые функции; состояние между экранами держится в атрибутах класса
# ModeratorApp (self.*). Это разделение позволяет переиспользовать те же
# db-функции в самом боте — структура данных у них общая (bot_data.db).
#
# Почему так: если бы панель обращалась к SQLite напрямую, то любые изменения
# схемы БД пришлось бы дублировать в двух файлах. Через единый модуль db все
# запросы живут в одном месте, а бот и панель всегда видят согласованные данные.
#
# GUI-поток и Telegram: панель запускает асинхронные корутины бота через
# asyncio.run() — однократно на каждое действие. Это допустимо, потому что
# long-polling бота работает в отдельном процессе/потоке и не требует
# собственного event loop в GUI.

# Хелперы (роли/даты/режимы) используются и в таблицах, и в диалогах —
# благодаря единому источнику правды подписи в UI и значения в БД не расходятся.
# Каждый хелпер решает одну маленькую задачу форматирования и не имеет
# побочных эффектов — их легко переиспользовать в любом месте файла.

