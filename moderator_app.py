# (подписи столбцов), кому-то в load_* (преобразование значений из БД).
# Ленивое определение единообразно покрывает пропущенные значения: пустая
# строка, None или отсутствующая роль превращаются в читаемый вид.

# ============================================================
# ТАБЛИЦА (обёртка над ttk.Treeview + тёмная/светлая тема)
# ============================================================
# Единая таблица для всех вкладок. Отличия от голого Treeview:
#   • скрытая колонка в конце хранит «значение строки» (обычно user_id);
#   • умеет перекрашиваться под тему (show_style);
#   • строки заполняются методом set_rows, скрытое значение берётся
#     из последнего элемента кортежа.
# Зачем скрытая колонка: действия панели (подтвердить, заблокировать, удалить)
# нужно привязать к конкретной записи. Вместо отдельного хранения «последней
# выбранной строки» значение кладётся прямо в строку таблицы — selected_value()
# мгновенно достаёт его откуда угодно.

class DataTable(ctk.CTkFrame):
    """Таблица с выбором строки. Хранит скрытое значение (обычно user_id)."""

    def __init__(self, master, columns: tuple, headers: tuple, hidden_col: str = "🆔",
                 col_widths: tuple | None = None):
        # Конструктор принимает «технические» имена колонок и их подписи.
        # columns и headers передаются параллельными кортежами: i-тая колонка
        # Treeview соответствует i-той подписи в шапке таблицы.
        super().__init__(master, fg_color=("gray92", "gray13"))
        # fg_color — кортеж из двух цветов (светлая тема, тёмная тема). Так
        # customtkinter автоматически подбирает нужный цвет под appearance mode.
        # «master» — родительский виджет: панель наследует его фон и жизненный цикл.
        #
        # Иерархия виджетов в Tk: окно → фрейм вкладки → DataTable → Treeview.
        # DataTable — это обычный контейнер-фрейм, внутри которого живут таблица
        # (ttk.Treeview) и вертикальная полоса прокрутки. Упаковка (pack) таблицы
        # и скроллбара ниже определяет их взаимное расположение внутри фрейма.
        self.columns = list(columns)        # технические имена колонок Treeview
        self.headers = list(headers)        # подписи колонок для пользователя
        # Скрытая колонка не показывается, но хранит значение строки
        # (если hidden_col не передан — «🆔» добавляется автоматически).
        self._data_col = hidden_col
        if self._data_col not in self.columns:
            # Добавляем скрытую колонку в конец — её имя и подпись приходят
            # вместе с остальными и будут исключены из отображения ниже.
            self.columns.append(self._data_col)
            self.headers.append(self._data_col)
        # Итог: список колонок всегда заканчивается скрытой. Благодаря этому
        # set_rows() знает, куда положить «значение строки», а selected_value()
        # — откуда его прочитать.

        # selectmode="browse" — можно выделить только одну строку.
        # show="headings" — не показываем левую «#0»-колонку по умолчанию.
        # Treeview — «мозг» таблицы ttk: хранит строки и колонки. DataTable
        # оборачивает его в ctk-фрейм, добавляя скроллбар и тему оформления.
        # selectmode="browse" — разрешён выбор ровно одной строки; события
        # двойного клика и кнопки панели читают выделенную строку через selection().
        self.tree = ttk.Treeview(self, columns=self.columns, show="headings",
                                 selectmode="browse")

        # Настраиваем каждую колонку: заголовок и ширину.
        # zip() склеивает пары (колонка, подпись) — порядок сохраняется.
        for col, hdr in zip(self.columns, self.headers):
            self.tree.heading(col, text=hdr)      # текст в шапке колонки
            width = 110                       # ширина по умолчанию
            if col_widths and col in col_widths:
                width = col_widths[col]       # или заданная явно
            self.tree.column(col, width=width, anchor="w", stretch=False)
        # Последняя (скрытая) колонка — узкая
        # Ширина 0 — колонка существует (данные там есть), но не видна.
        # anchor="w" — выравнивание текста ячеек по левому краю.
        self.tree.column(self._data_col, width=0, stretch=False)

        # Вертикальный скроллбар связан с таблицей через yview/yscrollcommand.
        # Команда скроллбара = tree.yview: полоса прокручивает именно таблицу.
        self.scrollbar = ttk.Scrollbar(self, orient="vertical", command=self.tree.yview)
        self.tree.configure(yscrollcommand=self.scrollbar.set)

        # Размещаем рядом: таблица слева растягивается, полоса справа фиксирована.
        # fill="both"+expand=True заставляет таблицу заполнять доступную площадь.
        self.tree.pack(side="left", fill="both", expand=True)
        self.scrollbar.pack(side="right", fill="y")

        self._apply_style()
        # При наведении мыши перекрашиваем на случай смены темы.
        # Лямбда игнорирует событие — show_style() параметров не требует.
        self.bind("<Enter>", lambda _e: self.show_style())
        self.show_style()

    def _apply_style(self):
        # Настраиваем внешний вид Treeview вручную (иначе он останется белым).
        style = ttk.Style(self.tree)   # стиль привязан к виджету таблицы
        try:
            style.theme_use("clam")   # «clam» — тема, лучше всего поддающаяся перекраске
        except Exception:  # noqa: BLE001
            pass   # на некоторых платформах clam недоступна — работаем с тем, что есть
        # Палитры для тёмной и светлой тем: фон, текст, выделение, поле, шапка.
        # Светлая/тёмная выбирается по глобальной настройке customtkinter.
        # get_appearance_mode() возвращает тему всего приложения, а не виджета —
        # поэтому при смене темы все таблицы перекрашиваются разом.
        if ctk.get_appearance_mode() == "Dark":
            bg, fg, sel, field, hdr = "#262626", "#e0e0e0", "#2f6da3", "#262626", "#333333"
        else:
            bg, fg, sel, field, hdr = "#ffffff", "#1a1a1a", "#4aa3ff", "#ffffff", "#e6e6e6"
        # Базовые цвета строки и шапки таблицы.
        # rowheight=30 — чуть выше стандартного для удобного тыка мышью.
        style.configure("Treeview", background=bg, fieldbackground=field,
                        foreground=fg, borderwidth=0, rowheight=30, font=("Segoe UI", 10))
        # Цвета выделенной (выбранной) строки: синий фон + белый текст.
        # style.map() задаёт цвета для состояний (selected = выделено).
        style.map("Treeview",
                  background=[("selected", sel)],
                  foreground=[("selected", "#ffffff")])
        # Шапка: отдельный стиль с жирным шрифтом и плоским рельефом.
        # relief="flat" убирает объёмную рамку вокруг шапки.
        style.configure("Treeview.Heading", background=hdr, foreground=fg,
                        relief="flat", font=("Segoe UI", 10, "bold"))
        # Тема «clam» распознаёт имена стилей Treeview (строки) и Treeview.Heading
        # (шапка). Стили ttk глобальны для приложения, поэтому перекраска всех
        # таблиц одним вызовом _apply_style() идемпотентна и безопасна.

    def show_style(self):
        # Перекрашивает таблицу под текущую тему (вызывается при смене).
        # Реальная работа — в _apply_style; этот метод лишь публичная обёртка.
        self._apply_style()

    def clear(self):
        # Удаляет все строки из таблицы.
        # get_children() возвращает id всех узлов верхнего уровня — их и стираем.
        # delete(item) заодно удалит и всех потомков элемента.
        # После clear() таблица остаётся полностью рабочей: колонки, стили и
        # ширина на месте, а очередной set_rows() заполнит пустую сетку заново —
        # пересоздавать виджет под каждый фильтр/поиск не нужно.
        for item in self.tree.get_children():
            self.tree.delete(item)

    def set_rows(self, rows: list):
        """rows — список кортежей значений. Скрытое значение строки берётся
        из последнего элемента кортежа (обычно это user_id / id записи)."""
        # Главный метод наполнения таблицы: всё содержимое заменяется одним
        # вызовом. Такой подход (полная замена, а не добавление) упрощает работу
        # с фильтрами/поиском: не нужно удалять «лишние» строки адресно — таблица
        # всегда показывает ровно то, что передал вызывающий код.
        # Сначала чистим старые строки, затем добавляем новые.
        # Это полная замена содержимого — так мы избегаем «мусора» от прошлых
        # заполнений (например, после применения фильтра или поиска).
        self.clear()
        for row in rows:
            values = list(row)
            # Дополняем пустыми строками, если кортеж короче числа колонок.
            # Такой допуск бережёт от ValueError у tree.insert().
            while len(values) < len(self.columns):
                values.append("")
            hidden_val = values[-1]   # скрытое значение — хвост кортежа
            # Скрытое значение кладём в последнюю (невидимую) колонку.
            # Значение приводим к строке — так его проще сравнивать в коде.
            values[len(self.columns) - 1] = str(hidden_val)   # в скрытую колонку
            # "end" — добавить новую строку в конец таблицы; values — её ячейки.
            self.tree.insert("", "end", values=values)
        # После цикла таблица синхронизирована с переданным списком rows.
        # Все скрытые значения (user_id и т.п.) лежат в последней колонке каждой
        # строки и доступны через selected_value()/selected_row().

    def selected_value(self):
        """Возвращает скрытое значение выбранной строки или None."""
        # Метод-«геттер» скрытой колонки: обработчики панели спрашивают именно
        # его, чтобы получить user_id (или id заявки) выбранной строки, после
        # чего выполняют действие в БД. От selected_row() отличается тем, что
        # возвращает именно «значение», а не кортеж видимых ячеек.
        sel = self.tree.selection()   # кортеж id выделенных элементов Treeview
        if not sel:
            return None               # ничего не выбрано
        values = self.tree.item(sel[0], "values")   # значения строки кортежем
        if not values or len(values) < len(self.columns):
            return None               # неполная строка — игнорируем
        return values[-1]   # последняя (скрытая) колонка = значение строки

    def selected_row(self):
        """Возвращает кортеж значений выбранной строки или None."""
        sel = self.tree.selection()
        if not sel:
            return None
        values = self.tree.item(sel[0], "values")
        if not values:
            return None
        # Видимые данные без скрытой колонки (хвостового элемента).
        return values[:-1]   # всё, кроме скрытой колонки
        # В отличие от selected_value(), здесь отдаются видимые ячейки — они
        # нужны, когда достаточно показать данные строки, не трогая скрытое
        # значение, которое лежит в самой последней колонке.


