    # Методы load_* читают данные из БД и заполняют виджеты. refresh_all —
    # «обновить всё» одной кнопкой (и по таймеру автообновления).

    def refresh_all(self):
        # Последовательная перезагрузка всех вкладок.
        # Вызывается по кнопке «Обновить данные» и таймером автообновления.
        self.load_pending()          # вкладка «Заявки»
        self.load_users()            # вкладка «Пользователи»
        self.load_errors()           # вкладка «Ошибки ИИ»
        self.load_ai_logs()          # вкладка «Логи ИИ»
        self.load_join_requests()    # вкладка «Вступление»
        self.load_stats()            # карточки «Обзора»
        self.update_status()         # статус-строка в шапке

    def update_status(self):
        # Статус-строка в шапке — единственная «глобальная» точка, где можно
        # увидеть состояние всей базы, не открывая вкладки: сколько пользователей,
        # заявок в очереди, запросов к ИИ и ошибок. Обновляется каждый refresh_all,
        # поэтому цифры всегда соответствуют тому, что показано на вкладках.
        # Обновляет текст статус-строки в шапке: база, кол-ва пользователей,
        # заявок, запросов ИИ и ошибок.
        pending = len(db.get_pending_users())         # сколько ждут подтверждения
        total = len(db.get_all_user_ids())            # всех пользователей в БД
        errors = len(db.get_ai_errors(limit=10000))   # ошибок ИИ (на весь лог)
        ai_total = db.count_ai_requests_total()       # всех запросов к ИИ
        # Собираем всё в одну строку и выводим в self.status_label.
        self.status_label.configure(
            text=f"🗂 База: {db.DATABASE_FILE}   |   👥 Пользователи: {total}   |   "
                 f"⏳ Заявки: {pending}   |   🤖 Запросов ИИ: {ai_total}   |   "
                 f"⚠️ Ошибок: {errors}"
        )

    def load_stats(self):
        # Считает статистику по пользователям (проход по всем) и заполняет
        # карточки на вкладке «Обзор», а также блок последней активности.
        users = db.get_all_users()
        # Счётчики, ключи которых совпадают с vocab карточек (см. _build_overview_tab).
        counts = {
            "total": len(users),
            "pending": 0, "students": 0, "teachers": 0,
            "moderators": 0, "rejected": 0, "blocked": 0,
        }
        # Один проход по списку пользователей заполняет сразу все ролевые счётчики.
        for u in users:
            # Раскладываем пользователей по ролям в счётчики.
            role = u.get("role")
            if role == "pending":
                counts["pending"] += 1
            elif role == "student":
                counts["students"] += 1
            elif role == "teacher":
                counts["teachers"] += 1
            elif role == "moderator":
                counts["moderators"] += 1
            elif role == "rejected":
                counts["rejected"] += 1
            if u.get("blocked"):
                counts["blocked"] += 1   # счётчик «заблокировано» независим

        # Оставшиеся счётчики берутся напрямую из БД.
        counts["join"] = len(db.get_pending_join_requests())
        counts["ai_errors"] = len(db.get_ai_errors(limit=10000))
        counts["ai_total"] = db.count_ai_requests_total()

        # Пишем цифры в карточки (self.stat_cards: key -> CTkLabel).
        for key, label in self.stat_cards.items():
            label.configure(text=str(counts.get(key, 0)))

        # Последняя активность
        # Берём до 20 последних логов, показываем последние 6 (свежие сверху).
        logs = db.get_ai_logs(limit=20)
        text = "Пока нет активности." if not logs else ""
        # [-6:] — последние шесть логов, [::-1] — с конца к началу (новые сверху).
        for log in logs[-6:][::-1]:
            ts = ts_to_str(log.get("time"))       # время запроса
            name = log.get("user_name") or "?"    # имя пользователя
            q = (log.get("question") or "")[:80]  # обрезаем вопрос до 80 символов
            text += f"🕐 {ts}  👤 {name}\n   ❓ {q}\n\n"   # форма строки активности
        # Обновляем текстовое поле (в «disabled» состояние вносить правки нельзя).
        self.overview_text.configure(state="normal")   # открываем на запись
        self.overview_text.delete("1.0", "end")        # очищаем старое содержимое
        self.overview_text.insert("1.0", text)         # вставляем новый текст
        self.overview_text.configure(state="disabled") # закрываем на запись

    def _fill_pending_row(self, user):
        # Строка заявки строится из полей словаря пользователя. Здесь же идёт
        # небольшая «нормализация» данных из БД: пустые значения заменяются
        # прочерком, а русская подпись роли берётся через role_display(). Важно,
        # что последним в кортеже всегда идёт user_id — по договорённости с DataTable
        # он уходит в скрытую колонку и становится «значением строки» при клике.
        # Если есть и full_name, и name из профиля — показываем оба.
        full_name = user.get("full_name") or ""
        max_name = user.get("name") or ""
        # Формируем подпись имени: «ФИО (MAX: имя из профиля)», если они различаются.
        if full_name and max_name and full_name != max_name:
            name_display = f"{full_name} (MAX: {max_name})"
        else:
            name_display = full_name or max_name or "—"
        # Вместо отсутствующих полей ставим прочерк; последний элемент — user_id
        # для скрытой колонки (он же ключ всех последующих действий).
        return (
            str(user.get("user_id", "")),
            name_display,
            str(user.get("phone") or "—"),
            str(user.get("class_name") or "—"),
            str(user.get("school") or "—"),
            role_display(user.get("role")),
            user.get("user_id"),   # скрытая колонка — для обработки клика
        )

