    def _pick_csv_path(self, default_name):
        # Общий диалог сохранения для всех CSV-кнопок. Из одного места задаются
        # расширение и «имя по умолчанию»; диалог возвращает выбранный путь или
        # пустую строку, если модератор просто закрыл окно «Сохранить». Второй
        # случай нельзя путать с успехом — вызывающий код проверяет путь на пустоту.
        # Диалог сохранения файла; возвращает путь или "" при отмене.
        path = filedialog.asksaveasfilename(
            defaultextension=".csv", initialfile=default_name,
            filetypes=[("CSV файл", "*.csv")])
        return path

    def _write_csv(self, path, headers, rows):
        # Пишет таблицу в CSV. encoding="utf-8-sig" — «висячий» BOM, чтобы
        # Excel открывал русские буквы правильно; delimiter=";" — запятые
        # внутри текста не ломают колонки.
        with open(path, "w", newline="", encoding="utf-8-sig") as f:
            writer = csv.writer(f, delimiter=";")
            writer.writerow(headers)
            writer.writerows(rows)

    def export_users_csv(self):
        # Выгрузка всех пользователей в CSV.
        path = self._pick_csv_path("users_export.csv")
        if not path:
            return   # пользователь отменил диалог
        users = db.get_all_users()
        # Заголовки колонок CSV — человекочитаемые имена полей.
        headers = ["ID", "Имя", "Имя_профиль", "Телефон", "Пароль", "Роль",
                   "Школа", "Класс", "Chat_ID", "Подтверждён", "Заблокирован",
                   "Лимит_ИИ", "Использовано_сегодня", "Зарегистрирован"]
        rows = []
        for u in users:
            # По одной строке CSV на пользователя (bool → «да/нет»).
            rows.append([
                u.get("user_id", ""),
                u.get("full_name", ""),
                u.get("name", ""),
                u.get("phone", ""),
                u.get("password", ""),
                u.get("role", ""),
                u.get("school", ""),
                u.get("class_name", ""),
                u.get("chat_id", ""),
                "да" if u.get("approved") else "нет",
                "да" if u.get("blocked") else "нет",
                u.get("ai_daily_limit", 50),
                u.get("ai_used_today", 0),
                ts_to_str(u.get("registered_at")),
            ])
        self._write_csv(path, headers, rows)
        # Показываем имя файла и число строк в строке статуса экспорта.
        self.export_status.configure(
            text=f"✅ Пользователи: {len(rows)} → {os.path.basename(path)}")

    def export_ai_csv(self):
        # Выгрузка истории запросов ИИ. Логи могут быть большими, поэтому берём
        # разумный максимум 10000 записей (панель и так показывает лишь последние
        # 300). Полезно для статистики использования вне панели — например, чтобы
        # открыть выборку в Excel или отдать аналитику. Итог с количеством строк
        # и именем файла виден в строке статуса вкладки.
        # Выгрузка истории запросов ИИ в CSV (до 10000 записей).
        path = self._pick_csv_path("ai_log_export.csv")
        if not path:
            return
        logs = db.get_ai_logs(limit=10000)
        headers = ["Время", "User_ID", "Пользователь", "Вопрос", "Ответ"]
        # Каждый лог → строка CSV: время, ID, имя, вопрос и ответ.
        rows = [[ts_to_str(l.get("time")), l.get("user_id", ""),
                 l.get("user_name", ""), l.get("question", ""), l.get("answer", "")]
                for l in logs]
        self._write_csv(path, headers, rows)
        self.export_status.configure(
            text=f"✅ Запросы ИИ: {len(rows)} → {os.path.basename(path)}")

    def export_errors_csv(self):
        # Лог ошибок — второй по полезности источник после истории запросов. Он
        # показывает, где бот сломался (ошибки API, проблемы с парсингом, и т.д.).
        # Максимум 10000 строк — такой же лимит, что и в логе ошибок UI (вкладка
        # «Ошибки ИИ»). Экспорт в CSV позволяет смотреть ошибки «снаружи» панели
        # и рассылать разработчику для исправления.
        # Выгрузка лога ошибок ИИ в CSV (до 10000 записей).
        path = self._pick_csv_path("ai_errors_export.csv")
        if not path:
            return
        errors = db.get_ai_errors(limit=10000)
        headers = ["Время", "User_ID", "Пользователь", "Режим", "Ошибка"]
        # Каждая ошибка → строка CSV со всеми её полями.
        rows = [[ts_to_str(e.get("time")), e.get("user_id", ""),
                 e.get("user_name", ""), e.get("mode", ""), e.get("error", "")]
                for e in errors]
        self._write_csv(path, headers, rows)
        self.export_status.configure(
            text=f"✅ Ошибки: {len(rows)} → {os.path.basename(path)}")

    def backup_db(self):
        # Резервная копия файла БД (просто копируем файл).
        default = f"bot_data_backup_{time.strftime('%Y%m%d_%H%M%S')}.db"
        path = filedialog.asksaveasfilename(
            defaultextension=".db", initialfile=default,
            filetypes=[("SQLite база", "*.db")])
        if not path:
            return
        try:
            # shutil.copy2 сохраняет и метаданные файла.
            shutil.copy2(db.DATABASE_FILE, path)
            self.export_status.configure(
                text=f"🗄 Резервная копия: {os.path.basename(path)}")
        except Exception as e:  # noqa: BLE001
            self.export_status.configure(text=f"❌ Ошибка копирования: {e}",
                                         text_color="#c62828")


