        target_id = self._require_target("Восстановление")
        if target_id is None:
            return
        role = db.get_user_field(target_id, "role")
        if role != "rejected":
            # Если пользователь не отклонён — восстанавливать нечего.
            messagebox.showinfo("Восстановление",
                                f"Пользователь ID {target_id} не отклонён "
                                f"(текущая роль: {role_display(role)}).")
            return
        if not messagebox.askyesno(
                "Восстановить заявку",
                f"Восстановить заявку ID {target_id} в статус «Ожидает»?"):
            return
        # Возвращаем роль pending и снимаем подтверждение — человек снова
        # появится во вкладке «Заявки».
        db.set_user_field(target_id, "role", "pending")
