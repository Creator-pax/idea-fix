class DetailWindow(ctk.CTkToplevel):
    """Окно с текстом (для просмотра заметки / вопроса-ответа ИИ)."""

    def __init__(self, master, title: str, text: str, width=560, height=420):
        # Toplevel — отдельное окно поверх главного; параметры задаём заранее.
        # В отличие от кнопок/фреймов, Toplevel — настоящее независимое окно:
        # у него свой заголовок и размеры. Master-окно лишь «родитель»: если его
        # закрыть, Tk приберёт и дочерние окна — следить за ними вручную не нужно.
        # width/height имеют значения по умолчанию, но вызывающий код может задать
        # свои (например, крупнее для длинного текста).
        # master нужен только для «родительства»: окно закрывается вместе с ним.
        super().__init__(master)
        self.title(title)                 # заголовок окна
        self.geometry(f"{width}x{height}") # стартовый размер окна
        self.minsize(400, 300)   # нельзя сделать совсем крошечным

        # Текстовая область растягивается, кнопка «Закрыть» внизу.
        # weight=1 у колонки/строки заставляет виджет занимать всё окно.
        self.grid_columnconfigure(0, weight=1)   # колонка растягивается по ширине
        self.grid_rowconfigure(0, weight=1)      # текст занимает всю высоту

        # Текстовое поле с переносом по словам (wrap="word").
        # Шрифт покрупнее — текст окна рассчитан на чтение, а не редактирование.
        box = ctk.CTkTextbox(self, wrap="word", font=("Segoe UI", 12))
        box.grid(row=0, column=0, sticky="nsew", padx=12, pady=12)
        box.insert("1.0", text)              # вставляем переданный текст
        box.configure(state="disabled")      # делаем read-only

        # Кнопка «Закрыть» уничтожает окно (destroy).
        btn = ctk.CTkButton(self, text="Закрыть", command=self.destroy,
                            width=140)
        btn.grid(row=1, column=0, pady=8)
        # Окно немодальное: можно открыть несколько таких поверх главного. Кнопка
        # «Закрыть» вызывает self.destroy() — виджеты Toplevel освобождаются.


class SendMessageWindow(ctk.CTkToplevel):
    """Окно отправки личного сообщения пользователю от имени бота."""

    def __init__(self, master, user_id):
        # Окно привязано к конкретному user_id — показываем его в заголовке.
        # self.user_id сохраняется, чтобы метод send() знал получателя.
        super().__init__(master)
        self.user_id = user_id   # сохраняем ID получателя для метода send()
        self.title(f"📨 Сообщение пользователю {user_id}")
        self.geometry("560x360")

        # Раскладка сетки: строка 2 (статус) остаётся фиксированной, текстовая
        # область (строка 1) растягивается по вертикали.
        # У строки 1 weight=1 — она вбирает лишнюю высоту окна.
        self.grid_columnconfigure(0, weight=1)
        self.grid_rowconfigure(2, weight=1)
        self.grid_rowconfigure(3, weight=0)
        # weight=0 у строки 3 (кнопки) означает «не растягивать»: кнопки всегда
        # фиксированной высоты внизу, а лишняя высота окна уходит полю ввода (row 1).

        # Подпись, поле ввода, строка статуса и кнопки «Отправить/Закрыть».
        ctk.CTkLabel(self, text=f"Текст сообщения для ID {user_id}:",
                     anchor="w", font=("Segoe UI", 12)).grid(
            row=0, column=0, sticky="ew", padx=12, pady=6)

        # Многострочное поле, куда модератор вводит текст сообщения.
        self.textbox = ctk.CTkTextbox(self, wrap="word", font=("Segoe UI", 12))
        self.textbox.grid(row=1, column=0, sticky="nsew", padx=12)

        # Строка статуса: сюда пишем результат (✅/❌) — изначально пустая.
        # Цвет меняется методом send() в зависимости от успеха.
        self.status = ctk.CTkLabel(self, text="", text_color="#2e7d32")
        self.status.grid(row=2, column=0, sticky="ew", padx=12, pady=4)

        # Контейнер кнопок; sticky="e" прижимает их к правому краю.
        btns = ctk.CTkFrame(self, fg_color="transparent")
        btns.grid(row=3, column=0, sticky="e", padx=12, pady=8)
        # «Отправить» — зелёная, запускает send(); «Закрыть» — простая.
        # Две кнопки укладываем в ряд через pack(side="left").
        ctk.CTkButton(btns, text="Отправить", command=self.send, width=130,
                      fg_color="#2e7d32", hover_color="#1f5d26").pack(side="left", padx=6)
        ctk.CTkButton(btns, text="Закрыть", command=self.destroy, width=110).pack(
            side="left", padx=6)

    def send(self):
        # Читаем текст от курсора до конца (get("1.0", "end")).
        # "1.0" (строка 1, символ 0) и "end" — индексы Tk-текстового поля.
        text = self.textbox.get("1.0", "end").strip()
        if not text:
            # Пустое сообщение отправлять не будем — просим ввести текст.
            # Красный цвет статуса сигнализирует об ошибке ввода.
            self.status.configure(text="❌ Введи текст сообщения.", text_color="#c62828")
            return
        # Профиль может вернуться пустым (нет записи) — (user or {}) страхует
        # от TypeError, если db.get_user() вдруг вернёт None.
        user = db.get_user(self.user_id)          # профиль получателя из БД
        chat_id = (user or {}).get("chat_id")     # нужен chat_id для отправки
        if not chat_id:
            # В БД надо сохранить chat_id при регистрации, иначе не достучаться.
            self.status.configure(
                text="❌ У пользователя нет сохранённого chat_id.", text_color="#c62828")
            return
        try:
            # bot.send_message — корутина; в GUI-потоке запускаем через asyncio.run.
            asyncio.run(self._send_async(chat_id, text))
        except Exception as e:  # noqa: BLE001
            # Ошибка Telegram API — показываем её текст в строке статуса.
            self.status.configure(text=f"❌ Ошибка: {e}", text_color="#c62828")
            return
        # Успех: показываем chat_id, куда ушло сообщение.
        self.status.configure(text=f"✅ Отправлено (chat {chat_id}).", text_color="#2e7d32")

    async def _send_async(self, chat_id, text):
        # Непосредственная отправка сообщения через бота.
        # await — единственная точка реальной отправки в Telegram.
        await bot.send_message(chat_id=chat_id, text=text)
        # Вспомогательной логики здесь нет: только одна очередь в Telegram.
        # Ошибки доставки ловит вызывающий send(), а сам метод — «тонкий».


class EditUserWindow(ctk.CTkToplevel):
    """Окно редактирования полей пользователя."""

    # Список редактируемых полей: (имя колонки в БД, подпись в окне).
    # Порядок определяет порядок строк формы «подпись + поле ввода».
    FIELDS = [
        ("full_name", "Имя (ФИО)"),
        ("name", "Имя из профиля"),
        ("phone", "Телефон"),
        ("school", "Школа"),
        ("class_name", "Класс"),
        ("password", "Пароль"),
        ("ai_topics", "Интересные темы ИИ"),
    ]

    def __init__(self, master, user_id):
        # Окно редактирования полей пользователя. В конструкторе формируется
        # «форма»: слева название поля, справа — поле ввода с текущим значением
        # из БД. Значения предварительно читаются через db.get_user() и сразу
        # подставляются в entry.insert(). Все поля собираются в словарь
        # self.entries (имя поля → виджет), по которому save() потом обходит форму.
        super().__init__(master)
        self.user_id = user_id                 # чей профиль редактируем
        self.entries = {}                 # field -> CTkEntry (для сохранения)
        user = db.get_user(user_id) or {} # текущие значения полей
        self.title(f"✏️ Редактирование ID {user_id}")
        self.geometry("460x560")

        # Две колонки: подписи (0) уже, поля ввода (1) шире.
        # Веса 1:2 — второе поле занимает вдвое больше ширины.
        # Значение weight — грубая пропорция: Tk растягивает колонки пропорционально
        # их весам, поэтому поле ввода всегда заметно шире подписи слева.
        self.grid_columnconfigure(0, weight=1)   # колонка подписей
        self.grid_columnconfigure(1, weight=2)   # колонка полей ввода

        # Строим форму: подпись слева, поле ввода справа, по одной строке на поле.
        # Текущее значение из БД подставляется в поле через entry.insert().
        row = 0   # счётчик строк сетки — растёт с каждым полем
        for field, label in self.FIELDS:
            ctk.CTkLabel(self, text=label).grid(
                row=row, column=0, sticky="w", padx=(12, 4), pady=5)
            entry = ctk.CTkEntry(self)   # поле ввода для значения
            entry.insert(0, str(user.get(field, "") or ""))   # подставляем текущее значение
            entry.grid(row=row, column=1, sticky="ew", padx=(4, 12), pady=5)
            self.entries[field] = entry   # запоминаем виджет по имени поля
            row += 1

        # Строка статуса + кнопки «Сохранить» и «Закрыть».
        self.status = ctk.CTkLabel(self, text="")
        # columnspan=2 — статус растягивается через обе колонки формы.
        self.status.grid(row=row, column=0, columnspan=2, sticky="ew",
                         padx=12, pady=4)
        row += 1

        # Кнопка сохранения проходит по всем полям (см. save()).
        ctk.CTkButton(self, text="💾 Сохранить", command=self.save,
                      fg_color="#2e7d32", hover_color="#1f5d26").grid(
            row=row, column=0, columnspan=2, sticky="ew", padx=12, pady=6)
        row += 1
        ctk.CTkButton(self, text="Закрыть", command=self.destroy).grid(
            row=row, column=0, columnspan=2, sticky="ew", padx=12, pady=6)

    def save(self):
        # Собираем значения из всех полей ввода и пишем их в БД.
        # Обновляются ВСЕ поля списка FIELDS: те, что модератор не трогал,
        # по-прежнему содержат старые значения и просто запишутся повторно.
        # strip() убирает лишние пробелы по краям введённого текста.
        for field, _label in self.FIELDS:
            value = self.entries[field].get().strip()   # текст из поля
            db.set_user_field(self.user_id, field, value)   # пишем в таблицу users
        self.status.configure(text="✅ Сохранено!", text_color="#2e7d32")


