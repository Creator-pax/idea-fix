# ============================================================
# ПАНЕЛЬ МОДЕРАТОРА — программа на customtkinter
# ============================================================
# Desktop-приложение для модераторов. Читает ту же базу данных,
# что и бот (bot_data.db), и позволяет:
#   1. Просматривать и подтверждать/отклонять заявки на регистрацию
#   2. Управлять пользователями (роли, блокировка, лимиты, удаление)
#   3. Смотреть лог запросов и ошибок ИИ
#   4. Смотреть заметки и историю ИИ любого пользователя
#   5. Обрабатывать заявки на вступление в школу
#   6. Делать массовую рассылку сообщений
#   7. Смотреть общую статистику и экспортировать данные в CSV
#   8. Отправлять личные сообщения пользователям от имени бота
#
# Запуск:  python moderator_app.py
#
# Структура кода (по разделам файла):
#   • константы и хелперы (роли, форматирование дат, режимы ИИ);
#   • класс DataTable — таблица на базе ttk.Treeview (тёмная/светлая тема);
#   • вспомогательные окна (DetailWindow, SendMessageWindow, EditUserWindow);
#   • класс ModeratorApp — главное окно: вкладки, загрузка данных,
#     действия над пользователями, рассылка, экспорт;
#   • main() — точка входа.
#
# При чтении снизу вверх: сначала идут «строительные» константы и классы,
# затем главный класс со всеми экранами, и только в самом низу — запуск.
# Такой порядок делает файл читабельным: определили «кирпичики» раньше,
# чем они понадобились большому классу.
# ============================================================

# --------------------------------------------------------------------------
# Как работает GUI-приложение (кратко):
#   • main() создаёт единственный объект ModeratorApp (корневое окно CTk);
#   • app.mainloop() запускает цикл обработки событий Tk — он «оживляет» окно:
#     клики, клавиатура, таймеры и перерисовка интерфейса;
#   • виджеты строятся «декларативно» в _build_* методах и далее просто живут;
#   • по кнопкам обработчики вызывают db-функции и потом refresh_all();
#   • сообщения в Telegram шлёт отдельный процесс бота через bot_instance.
# Эта схема одинакова для всех вкладок — от «Обзор» до «Экспорт».
# --------------------------------------------------------------------------

