    # Массовая рассылка позволяет одним сообщением достучаться до всех учеников,
    # учителей, модераторов или всех подтверждённых пользователей сразу. Список
    # получателей берётся из БД по роли (get_chat_ids_by_role), а сама отправка
    # идёт по одному сообщению через бота. Сообщения уходят в том же GUI-потоке
    # короткими asyncio.run() — рассылка выполняется последовательно, зато все
    # ошибки адресатов собираются в единый итог «отправлено/ошибок».

    def do_broadcast(self):
        # Массовая рассылка по выбранной аудитории.
        text = self.broadcast_text.get("1.0", "end").strip()
        if not text or text == "Введи текст рассылки...":
            # Пустой текст или текст-заполнитель по умолчанию.
            self.broadcast_status.configure(text="❌ Введи текст рассылки.",
                                            text_color="#c62828")
            return

        target = self.broadcast_target.get()
        # Подписи аудитории → значения ролей для get_chat_ids_by_role.
        role_map = {
            "Всем подтверждённым": "all",
            "📚 Ученикам": "student",
            "👨‍🏫 Учителям": "teacher",
            "🛡 Модераторам": "moderator",
        }
        role = role_map.get(target, "all")
        chat_ids = db.get_chat_ids_by_role(role)   # чаты всех адресатов

        if not chat_ids:
            self.broadcast_status.configure(text="❌ Нет получателей.",
                                            text_color="#c62828")
            return

        # Финальное подтверждение: показываем число получателей и начало текста.
        if not messagebox.askyesno(
                "Рассылка",
                f"Отправить сообщение {len(chat_ids)} получателям?\n\n«{text[:80]}...»"):
            return

        # Посылаем сообщения по одному (GUI-поток, поэтому asyncio.run).
        sent, failed = 0, 0
        for chat_id in chat_ids:
            try:
                asyncio.run(self._broadcast_one(chat_id, text))
                sent += 1
            except Exception as e:  # noqa: BLE001
                failed += 1   # сбой одному адресату не прерывает рассылку
                print(f"BROADCAST: {chat_id}: {e}")

        # Итог: сколько доставлено, сколько с ошибками.
        self.broadcast_status.configure(
            text=f"✅ Отправлено: {sent}   ❌ Ошибок: {failed}",
            text_color="#2e7d32")

    async def _broadcast_one(self, chat_id, text):
        # Отправка одного сообщения рассылки (корутина для asyncio.run).
        await bot.send_message(chat_id=chat_id, text=text)

