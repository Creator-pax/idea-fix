    # ЗАЯВКИ: ПОДТВЕРДИТЬ / ОТКЛОНИТЬ
    # ============================================================
    # Работа с заявками на регистрацию: подтверждение ставит approved=1,
    # отклонение переводит роль в rejected. После обоих действий —
    # обновление всех данных (refresh_all).

    def _notify_user(self, user_id, text=None):
        """Отправляет пользователю уведомление от имени бота (если возможно)."""
        if text is None:
            # Текст по умолчанию — когда модератор подтвердил регистрацию.
            text = (
                "🎉 Поздравляем! Твоя заявка подтверждена!\n\n"
                "Теперь ты можешь пользоваться MAX Школьным помощником.\n"
                "Напиши /start, чтобы открыть меню."
            )
        try:
            asyncio.run(self._notify_user_async(user_id, text))
        except Exception as e:  # noqa: BLE001
            # Сбой уведомления не должен ронять панель — только логируем.
            print(f"MODERATION: Could not notify user {user_id}: {e}")

    async def _notify_user_async(self, user_id, text):
        # Реальное уведомление: берём chat_id из БД и шлём через бота.
        user = db.get_user(user_id)
        chat_id = (user or {}).get("chat_id")
        if not chat_id:
            print(f"MODERATION: No chat_id stored for user {user_id}, cannot notify")
            return   # без chat_id отправлять некуда
        await bot.send_message(chat_id=chat_id, text=text)

    def approve_selected(self):
        # Подтверждает заявку выбранного пользователя во вкладке «Заявки».
        target_id = self._selected_pending_id()
        if target_id is None:
            messagebox.showinfo("Подтверждение", "Выбери заявку в таблице.")
            return
        # Запрашиваем подтверждение у модератора перед изменением БД.
        if not messagebox.askyesno(
                "Подтвердить заявку", f"Подтвердить регистрацию пользователя ID {target_id}?"):
            return   # пользователь отменил диалог

        # Перед подтверждением снимаем блокировку (если была), затем подтверждаем.
        db.set_blocked(target_id, False)    # убираем блокировку (если была)
        db.approve_user(target_id)          # ставим approved=1 в БД
        self._notify_user(target_id)        # отправляем «🎉 Поздравляем...» в чат
        messagebox.showinfo("Готово", f"Заявка ID {target_id} подтверждена. Пользователь уведомлён.")
        self.refresh_all()   # данные на всех вкладках перезагружаются

    def reject_selected(self):
        # Отклонение — снятие подтверждения и перевод роли в rejected. Подтвердить
        # или отклонить можно только заявку, выделенную в таблице (столбец из
        # pending_table); после действия список заявок перезагружается, и строка
        # уходит из таблицы — интерфейс сразу отражает изменение в БД.
        # Отклоняет заявку выбранного пользователя во вкладке «Заявки».
        target_id = self._selected_pending_id()
        if target_id is None:
            messagebox.showinfo("Отклонение", "Выбери заявку в таблице.")
            return
        if not messagebox.askyesno(
                "Отклонить заявку", f"Отклонить заявку пользователя ID {target_id}?"):
            return
        # Отклонение = роль rejected + снятие подтверждения.
        db.set_user_field(target_id, "role", "rejected")
        db.set_user_field(target_id, "approved", False)
        messagebox.showinfo("Готово", f"Заявка ID {target_id} отклонена.")
        self.refresh_all()

