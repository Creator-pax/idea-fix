    def _fill_user_row(self, user):
        # Строка таблицы «Пользователи»: превращает сырой словарь из БД в кортеж,
        # который DataTable покажет в колонках. Дополнительно вычисляются два
        # производных поля — «Статус» (из approved/role) и «Блокировка» (из blocked),
        # чтобы вся нужная модератору информация была видна без открытия карточки.
        # Последним элементом снова кладётся user_id (скрытая колонка).
        approved = user.get("approved")   # подтверждена ли регистрация
        role = user.get("role")           # текущая роль пользователя
        blocked = user.get("blocked")     # заблокирован ли
        # Все три поля нужны для вычисления «Статус» и «Блокировка».

        # Логика статуса: модератор → «Модератор», иначе по approved/роли.
        if role == "moderator":
            status = "🛡 Модератор"
        elif approved:
            status = "✅ Подтверждён"
        elif role == "rejected":
            status = "❌ Отклонён"
        else:
            status = "⏳ Ожидает"

        block_text = "🚫 Заблокирован" if blocked else "✅ Активен"

        # Последний элемент кортежа — user_id (скрытая колонка DataTable).
        return (
            str(user.get("user_id", "")),
            str(user.get("full_name") or user.get("name") or "—"),
            str(user.get("phone") or "—"),
            role_display(role),
            status,
            str(user.get("class_name") or "—"),
            str(user.get("school") or "—"),
            str(user.get("chat_id") or "—"),
            ts_to_str(user.get("registered_at")),
            block_text,
            user.get("user_id"),   # скрытая колонка
        )

    def load_users(self):
        # Загрузка таблицы пользователей, которая учитывает два условия-«фильтра»:
        # текстовый поиск (по набору полей) и роль из выпадающего списка. Оба
        # фильтра применяются к полному списку из БД, а уже после них строится
        # таблица и обновляется счётчик «Показано: N». Так поиск и роль работают
        # вместе, а между перезагрузками состояние вкладки не «теряется».
        users = db.get_all_users()   # все пользователи из БД
        search = self.users_search.get().strip().lower()   # текст из поля поиска

        # Фильтр по роли
        # Сопоставляем выбранную подпись в OptionMenu со значением роли.
        role_filter = None
        for value, label in _FILTER_ROLES:
            if label == self.users_filter.get():
                role_filter = value
                break
        # Значение "all" = фильтра нет — оставляем список как есть.
        if role_filter and role_filter != "all":
            users = [u for u in users if u.get("role") == role_filter]

        # Текстовый поиск: совпадение по ID/имени/телефону/школе/классу.
        if search:
            filtered = []
            for u in users:
                # Собираем все поля в одну строку «стог сена» и ищем подстроку.
                haystack = " ".join([
                    str(u.get("user_id", "")),
                    str(u.get("full_name") or ""),
                    str(u.get("name") or ""),
                    str(u.get("phone") or ""),
                    str(u.get("school") or ""),
                    str(u.get("class_name") or ""),
                ]).lower()
                # Если подстрока из поля поиска есть — оставляем пользователя.
                if search in haystack:
                    filtered.append(u)
            users = filtered

        # Пересобираем таблицу и обновляем счётчик «Показано: N».
        rows = [self._fill_user_row(u) for u in users]
        self.users_table.set_rows(rows)   # все строки попадают в DataTable
        self.users_count_label.configure(text=f"Показано: {len(rows)}")

