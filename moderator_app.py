# --- Мелкие хелперы форматирования ----------------------------------------
# Все три функции ниже — «чистые» (pure): по входу однозначно вычисляют выход
# и не меняют внешнее состояние. Поэтому их безопасно звать из любого места GUI:
# из обработчиков, из load_*, из экспорта. Итоговый вид данных держится в одном
# месте, а не размазан по десяткам f-строк.


def role_display(role: str) -> str:
    """Человекочитаемое название роли."""
    # Проходим по ROLE_LABELS в поисках совпадающего значения из БД.
    # Линейный поиск мал и предсказуем — индексы/словари здесь избыточны.
    for value, label in ROLE_LABELS:
        if value == role:
            return label
    # Если роль не найдена в списке — возвращаем её как есть (или прочерк).
    # Это защита от новых ролей, которых ещё нет в ROLE_LABELS.
    return role or "—"


def ts_to_str(ts) -> str:
    """Преобразует Unix-время в читаемую строку."""
    # ts может прийти в виде числа, строки или None — единая точка форматирования.
    # Именно поэтому здесь нет аннотации типа: caller может быть чем угодно.
    if not ts:
        return "—"   # пустое/нулевое время → прочерк
    try:
        # Преобразуем timestamp в локальное время и форматируем как ДД.ММ.ГГГГ ЧЧ:ММ.
        # time.localtime() превращает секунды с эпохи Unix в struct_time.
        return time.strftime("%d.%m.%Y %H:%M", time.localtime(int(ts)))
    except (ValueError, TypeError):
        return "—"   # битые данные не даём уронить UI


def mode_display(mode: str) -> str:
    """Человекочитаемое название режима ИИ."""
    # Ищем режим в словаре _MODE_META; если не нашли — вернём его как есть.
    # dict.get(key, default) покрывает и отсутствие, и пустое значение.
    return _MODE_META.get(mode, mode or "—")


