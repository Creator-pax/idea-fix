    # ============================================================
    # ТЕМА
    # ============================================================
    # Тёмная тема включена по умолчанию, но модератор может переключить её
    # прямо из шапки окна. Смена темы не пересобирает виджеты: customtkinter
    # перерисовывает их сам, а ttk-таблицы нужно перекрасить вручную — только
    # поэтому ниже есть отдельный цикл по всем DataTable.

    def _toggle_theme(self):
        # Обработчик switch срабатывает в момент клика — кнопки «Применить» нет.
        # Тема меняется мгновенно и применяется глобально ко всем ctk-виджетам.
        # Переключаем тему всего приложения по состоянию switch.
        # get()==1 → switch включён → тёмная тема, иначе светлая.
        if self.theme_switch.get() == 1:
            ctk.set_appearance_mode("dark")
        else:
            ctk.set_appearance_mode("light")
        # Перекрашиваем таблицы
        # ttk-виджеты не перекрашиваются сами — явно применяем стиль к каждой.
        # Только таблицы требуют ручной перекраски; customtkinter-виджеты
        # реагируют на appearance mode автоматически.
        for table in (self.pending_table, self.users_table, self.ailogs_table,
                      self.errors_table, self.join_table):
            table.show_style()
        # ttk-таблицы не подхватывают тему автоматически; дочерние Toplevel-окна
        # перекрасятся сами — их ctk-виджеты реагируют на appearance mode при
        # следующей отрисовке, поэтому в списке обхода их нет.

    # ============================================================
    # АВТООБНОВЛЕНИЕ
    # ============================================================
    # Автообновление держит данные панели свежими без участия модератора:
    # каждые N секунд перезагружаются все вкладки (refresh_all). Интервал N
    # задаётся в шапке («сек:»), а сам цикл запускается простым таймером after.

    # Механика таймера: after(мс, callback) ставит ОДИН отложенный вызов.
    # Когда он срабатывает, _auto_refresh_tick при включённом флаге вызывает
    # refresh_all() и снова планирует себя — получается бесконечный цикл
    # с паузой N секунд между итерациями.
    # В Tk нет встроенного «повторяющегося» таймера — только однократный after().
    # Поэтому повторение реализуется самопланированием: колбэк в конце ставит
    # новый after(). Отмена возможна через after_cancel() с сохранённым ID.

    def _schedule_auto_refresh(self, *_):
        # Перезапуск простого таймера автообновления реализуем через after()
        # (метод Tk: вызовет функцию через N миллисекунд). Прочие аргументы
        # (*_) принимаем, т.к. метод служит и обработчиком combo/checkbox.
        self._cancel_auto_refresh()   # снимаем старый таймер (если был)
        if self.auto_refresh_check.get() == 1:   # автообновление включено?
            try:
                interval = int(self.refresh_interval.get())
            except ValueError:
                interval = 10          # мусор в поле → 10 секунд
            # Ставим новый таймер: через interval*1000 мс вызовем _auto_refresh_tick.
            # ID таймера сохраняем, чтобы его можно было отменить.
            self._auto_refresh_after_id = self.after(
                interval * 1000, self._auto_refresh_tick)

    def _cancel_auto_refresh(self):
        # Убирает отложенный вызов (если он ещё не сработал).
        # Пары «планирование/отмена» дают полный контроль над таймером: каждое
        # изменение интервала или выключение чекбокса мгновенно отменяет старый
        # отсчёт и, при необходимости, ставит новый. Без отмены старый таймер
        # «дожил» бы до своего срабатывания и перезагрузил данные снаружи цикла.
        try:
            self.after_cancel(self._auto_refresh_after_id)
        except Exception:  # noqa: BLE001
            pass   # таймера ещё не было — нечего отменять

    def _auto_refresh_tick(self):
        # Сработал таймер: если автообновление включено — перезагружаем данные
        # и запускаем таймер заново (цикл «каждые N секунд»).
        if self.auto_refresh_check.get() == 1:
            self.refresh_all()
            self._schedule_auto_refresh()
        # Все эти методы работают в главном GUI-потоке, поэтому db-запросы и
        # обновление виджетов безопасны: гонок с другими потоками не возникает.

    # ============================================================
    # ПОСТРОЕНИЕ ВКЛАДОК
    # ============================================================
    # Раздел отвечает за визуальную сборку интерфейса: девять _build_* методов
    # создают виджеты девяти вкладок (ширина экрана не позволяет держать всё на
    # одной странице). Каждый метод работает только с «своей» вкладкой и не
    # вызывает других — порядок сборки задан списком вызовов в __init__. Всё,
    # что относится к данным (загрузка, обработка), живёт ниже, в разделах
    # ЗАГРУЗКА ДАННЫХ и кнопочных обработчиков.
    # Каждый метод *_build_tab создаёт виджеты ОДНОЙ вкладки. Построение
    # вынесено в отдельные методы, чтобы __init__ оставался коротким.
    #
    # Общий паттерн построения вкладки:
    #   1) настроить сетку (grid_columnconfigure/grid_rowconfigure) — какие ряды
    #      и колонки растягиваются, какие зафиксированы;
    #   2) создать DataTable (или поля ввода);
    #   3) разместить кнопки действий и привязать к ним методы панели.
    # Повторяемость паттерна упрощает чтение: поняв одну вкладку, легко читаются
    # и остальные.

    # -------------------------------------------------------------------------
    # Сетка и компоновка: основа каждой вкладки — grid-менеджер
    # (grid_columnconfigure/grid_rowconfigure). Он задаёт «скелет»: какие строки
    # и колонки растягиваются (weight>0), а какие остаются фиксированными.
    # Виджеты затем размещаются по координатам (row, column) с отступами
    # padx/pady и привязкой (sticky). Такой подход детерминирован: изменение
    # размеров окна не ломает раскладку, вкладка адаптируется сама.
    # -------------------------------------------------------------------------

    def _build_overview_tab(self):
        # Вкладка «Обзор»: карточки-счётчики + блок последней активности ИИ.
        tab = self.tab_overview
        # Логика сверху/снизу: статистика (row 0) всегда видна целиком, а большую
        # часть окна занимает лента последней активности (row 1, weight=1). При
        # ручном изменении размера окна растягивается только нижняя зона.
        # Верхняя часть (карточки) по высоте свободная, нижняя (лог) растягивается.
        tab.grid_columnconfigure(0, weight=1)
        tab.grid_rowconfigure(1, weight=1)

        # Сетка карточек 5×2 со статистикой. Ключи совпадают с counts в load_stats.
        cards = ctk.CTkFrame(tab)                      # контейнер всех карточек
        cards.grid(row=0, column=0, sticky="ew", padx=10, pady=8)

        self.stat_cards = {}   # key -> label, где показывается число
        # Ключи карточек совпадают с ключами словаря counts из load_stats() —
        # между построением вкладки и её обновлением действует «единая шина данных».
        # Каждая карточка: (технический ключ из counts, подпись над числом).
        stats = [
            ("total", "👥 Всего"),
            ("pending", "⏳ Заявки"),
            ("students", "📚 Ученики"),
            ("teachers", "👨‍🏫 Учителя"),
            ("moderators", "🛡 Модераторы"),
            ("rejected", "❌ Отклонено"),
            ("blocked", "🚫 Заблокировано"),
            ("join", "🏫 Вступление"),
            ("ai_errors", "⚠️ Ошибки ИИ"),
            ("ai_total", "🤖 Запросов (всего)"),
        ]
        # Раскладываем карточки в две строки по пять: row=i//5, col=i%5.
        # enumerate() даёт индекс, по которому вычисляются строка и колонка сетки —
        # получается ровно 5 карточек сверху и 5 снизу без ручной раскладки.
        for i, (key, title) in enumerate(stats):
            # Скруглённая карточка фиксированного размера.
            card = ctk.CTkFrame(cards, width=118, height=72, corner_radius=12)
            card.grid(row=i // 5, column=i % 5, padx=6, pady=6, sticky="nsew")
            ctk.CTkLabel(card, text=title, font=("Segoe UI", 11)).pack(pady=(8, 0))
            # Большая цифра — её и обновляет load_stats().
            value = ctk.CTkLabel(card, text="0", font=("Segoe UI", 18, "bold"),
                                 text_color="#5fa7ff")
            value.pack()
            self.stat_cards[key] = value   # запоминаем label — в него пишем цифры
        # Все 5 колонок сетки карточек равной ширины (растягиваются).
        # Без weight=1 карточки «сжались» бы к левому краю при большом окне.
        for c in range(5):
            cards.grid_columnconfigure(c, weight=1)
        # Итог: 10 карточек (5x2). load_stats() пройдётся по self.stat_cards и
        # впишет актуальные цифры в каждую карточку по её ключу.

        # Недавняя активность ИИ
        # Текстовое поле только для чтения с последними 20 запросами.
        # Свободный текст вместо таблицы — поэтому CTkTextbox, а не DataTable.
        # Наполняет блок load_stats() последними логами запросов.
        wrap = ctk.CTkFrame(tab)                       # рамка блока активности
        wrap.grid(row=1, column=0, sticky="nsew", padx=10, pady=8)
        wrap.grid_columnconfigure(0, weight=1)
        wrap.grid_rowconfigure(1, weight=1)

        # Заголовок блока над текстовым полем.
        ctk.CTkLabel(wrap, text="📊 Последняя активность по ИИ:",
                     font=("Segoe UI", 13, "bold")).grid(
            row=0, column=0, sticky="w", padx=8, pady=4)

        # Поле с историей: state="disabled" — только чтение, активируем на время записи.
        self.overview_text = ctk.CTkTextbox(wrap, wrap="word", font=("Segoe UI", 12),
                                            state="disabled")
        self.overview_text.grid(row=1, column=0, sticky="nsew", padx=8, pady=4)

