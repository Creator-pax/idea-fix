    # ЗАЯВКИ НА ВСТУПЛЕНИЕ В ШКОЛУ
    # ============================================================
    # Отдельный вид заявок — «вступление в школу/класс». Обработка: принять
    # (обновить школу/класс ученика + уведомить) или отклонить.

    def _selected_join_id(self):
        # Читает id заявки из выделенной строки таблицы «Вступление». Приёмы те же,
        # что и у _selected_pending_id: пустой выбор и нечисловые значения (мусор)
        # превращаются в None, чтобы _join_decision() мог просто проверить результат.
        # ID заявки из выбранной строки таблицы «Вступление».
        val = self.join_table.selected_value()
        if val is None or val == "":
            return None
        try:
            return int(val)
        except (TypeError, ValueError):
            return None

    def _join_decision(self, accept: bool):
        # Общая логика принятия/отклонения заявки на вступление.
        request_id = self._selected_join_id()
        if request_id is None:
            messagebox.showinfo("Заявка", "Выбери заявку в таблице.")
            return
        request = db.get_join_request_by_id(request_id)
        if not request:
            messagebox.showwarning("Ошибка", "Заявка не найдена.")
            return
        if request.get("status") != "pending":
            messagebox.showinfo("Заявка", "Заявка уже обработана.")
            return   # повторно обработать нельзя
        name = request.get("full_name") or request.get("name") or f"ID {request.get('user_id')}"
        action = "принять" if accept else "отклонить"
        # Спрашиваем подтверждение, подставляя имя ученика в текст диалога.
        if not messagebox.askyesno(
                "Решение по заявке", f"{action.capitalize()} заявку ученика «{name}»?"):
            return

        if accept:
            # Принятие: approved + обновление школы/класса ученика + уведомление.
            db.approve_join_request(request_id, 0)
            # обновляем школу/класс и уведомляем ученика
            student_id = request.get("user_id")
            db.set_user_field(student_id, "school", request.get("target_school"))
            db.set_user_field(student_id, "class_name", request.get("target_class"))
            self._notify_user(student_id, (
                "🎉 Твоя заявка на вступление подтверждена!\n\n"
                f"🏫 Школа: {request.get('target_school')}\n"
                f"📚 Класс: {request.get('target_class')}\n\n"
                "Добро пожаловать! Напиши /start."
            ))
            messagebox.showinfo("Готово", "Заявка принята, ученик уведомлён.")
        else:
            # Отклонение: статус rejected + уведомление.
            db.reject_join_request(request_id, 0)
            self._notify_user(request.get("user_id"),
                              "❌ Твоя заявка на вступление в школу была отклонена.")
            messagebox.showinfo("Готово", "Заявка отклонена, ученик уведомлён.")
        self.refresh_all()

    def approve_join_selected(self):
        # Кнопки «Принять / Отклонить» на этой вкладке — тонкие обёртки над общей
        # логикой _join_decision(): параметр accept определяет, какой путь (принять
        # или отклонить) будет выполнен. Разделение на обёртки и общий метод
        # позволяет не дублировать чтение заявки и проверки для двух кнопок.
        # Кнопка «✅ Принять» → обрабатываем заявку как принятую.
        self._join_decision(accept=True)

    def reject_join_selected(self):
        # Кнопка «❌ Отклонить» → обрабатываем заявку как отклонённую.
        self._join_decision(accept=False)

