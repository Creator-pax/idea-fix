# ТЕКСТОВЫЕ СООБЩЕНИЯ ВО ВРЕМЯ СОЗДАНИЯ ЗАМЕТКИ
# ============================================================

# Этот обработчик ловит любое текстовое сообщение, но только когда юзер
# находится в одном из состояний NotesStates (ввод заголовка или текста).
@router.message_created(StateFilter(NotesStates))
async def handle_notes_text(update: MessageCreated, fsm_context) -> None:
    """
    Обрабатывает сообщения, когда ждём заголовок или содержимое заметки.

    StateFilter(NotesStates) означает: только если пользователь сейчас
    в любом из состояний NotesStates (ввод заголовка или текста).
    """
    user_id = get_user_id(update)  # ID пишущего пользователя
    text = update.text or ""       # текст сообщения (str); None превращаем в пустую строку
    if not text:
        return  # пустое сообщение (например фото без подписи) — не обрабатываем

    # По хорошей практике фильтр StateFilter пропустил сюда только нужного
    # пользователя; остаётся лишь понять, какой ИМЕННО шаг ожидается:
    # заголовок (wait_title) или содержимое (wait_content).

    # Узнаём, в каком именно состоянии FSM находится пользователь.
    # get_state() вернёт строку вида "NotesStates:wait_title" либо None.
    state = await fsm_context.get_state()

    # ============================================================
    # ОЖИДАЕМ ЗАГОЛОВОК
    # ============================================================
    if state == NotesStates.wait_title:
        # Валидация длины заголовка: разрешено от 1 до 100 символов.
        # len(text) — длина строки в символах (не в байтах).
        if len(text) < 1 or len(text) > 100:
            # Заголовок не подходит по длине — просим ввести ещё раз.
            await update.answer_text(
                "❌ Заголовок должен быть от 1 до 100 символов.\n"
                "Попробуй ещё раз:"
            )
            return  # состояние не меняем — пользователь остаётся в wait_title

        # Сохраняем заголовок во временные данные FSM и переходим
        # к ожиданию содержимого.
        # update_data кладёт значение в хранилище FSM под ключом "note_title".
        await fsm_context.update_data(note_title=text)
        # Меняем состояние на wait_content — следующий текст станет содержимым.
        await fsm_context.set_state(NotesStates.wait_content)
        # Последовательность: заголовок во временных данных, потом перевод
        # в состояние «ждём текст». Данные переживут смену состояния —
        # это и есть смысл update_data в FSM.

        # Подтверждаем заголовок и просим ввести содержимое.
        await update.answer_text(
            f"✅ Заголовок: {text}\n\n"
            "Теперь напиши содержимое заметки:"
        )

    # ============================================================
    # ОЖИДАЕМ СОДЕРЖИМОЕ
    # ============================================================
    elif state == NotesStates.wait_content:
        if len(text) < 1:
            # Не должно случиться (пустой текст отсечён выше), но страхуемся.
            await update.answer_text("❌ Заметка не может быть пустой. Напиши что-нибудь:")
            return

        # Заголовок уже сохранён на предыдущем шаге — теперь «доклеиваем»
        # к нему содержимое. Этот приём (временные данные + смена состояния)
        # — стандартная идиома FSM для многошаговых форм.
        # ВАЖНО: если пользователь нажмёт «← Отмена» на этом шаге, ветка
        # menu_notes вызовет clear() и весь накопленный заголовок сотрётся.

        # Достаём ранее сохранённый заголовок из временных данных FSM.
        # get_data() возвращает словарь всех данных текущего состояния.
        data = await fsm_context.get_data()
        title = data.get("note_title", "Без заголовка")  # на случай, если ключа нет

        # Сохраняем заметку в БД (ID пользователя, заголовок, содержимое).
        db.save_note(user_id, title, text)

        # Сбрасываем состояние FSM — пользователь больше не «в создании»,
        # иначе его следующие сообщения снова попадали бы в этот обработчик.
        await fsm_context.clear()

        # Кнопки после сохранения: «Создать ещё одну» и «Назад к списку».
        kb = _back_to_list_keyboard("📝 Создать ещё одну", "note_create")
        # Кнопка «Создать ещё одну» повторно шлёт payload "note_create":
        # цикл создания запускается заново уже из этого экрана. Пары
        # «создать ещё / назад к списку» достаточно, чтобы оставаться
        # в разделе, не прыгая в главное меню.
        # Показываем подтверждение с превью: заголовок + текст, обрезанный
        # до 100 символов (с многоточием, если текст длиннее).
        await update.answer_text(
            "✅ Заметка сохранена!\n\n"
            f"📖 {title}\n"
            f"📄 {text[:100]}{'...' if len(text) > 100 else ''}",
            keyboard=kb.build(),
        )
        # Срезу `[:100]` + условное многоточие — «превью» содержимого:
        # короткая заметка видна целиком, длинная — в усечённом виде.


