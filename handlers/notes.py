# ============================================================
# ОБРАБОТЧИК ЗАМЕТОК — handlers/notes.py
# ============================================================
# Этот файл отвечает за:
#   1. Создание новых заметок (заголовок, затем содержимое);
#   2. Просмотр списка заметок;
#   3. Просмотр содержимого отдельной заметки;
#   4. Удаление заметок.
#
# Показательный пример на два «удобства» maxo:
#   • CallbackPayload с префиксами — note_view_<index>, note_delete_<index>;
#   • FSM с несколькими состояниями NotesStates(ввод заголовка/текста).
#
# ВАЖНО: весь раздел обслуживает ОДИН обработчик колбэков, потому что у
# веток menu_notes / note_create / note_view_ / note_delete_ много общего
# (проверка пользователя, пересборка списка). Разветвление по payload
# происходит уже внутри функции через if / elif.
# ============================================================

# time — стандартный модуль работы со временем: нужен, чтобы превращать
# Unix-время создания заметки в читаемый текст "дд.мм чч:мм".
import time

# Router — создание роутера для группы обработчиков заметок.
from maxo import Router
# StateFilter — фильтр «пользователь сейчас в одном из состояний группы».
from maxo.routing.filters import StateFilter
# MessageCallback — нажатие кнопки; MessageCreated — новое сообщение в чат.
from maxo.types import MessageCallback, MessageCreated
# KeyboardBuilder — конструктор клавиатур: кнопки через add_callback.
from maxo.utils.builders import KeyboardBuilder

# База данных (см. database.py): заметки хранятся на стороне БД.
import database as db

# Свой фильтр колбэков по payload (реализован в handlers/filters.py).
from handlers.filters import CallbackPayload
# Группа состояний FSM для заметок (ввод заголовка/содержимого).
from handlers.states import NotesStates
# Утилита безопасного получения user_id из апдейта.
from handlers.user_utils import get_user_id

# Роутер раздела заметок: все обработчики этого файла регистрируются на нём.
router: Router = Router(name="notes")
# Роутер назван «notes» — в логах видно, что именно обрабатывает апдейт.
# У роутеров нет responsibilities-атрибутов, поэтому имя — единственный
# способ отличить один роутер от другого при отладке.


# ============================================================
# КЛАВИАТУРЫ
# ============================================================
# В файле две функции-«билдера» клавиатур: одна возвращает список
# (создать/назад в меню), вторая — экран действия (действие/назад к списку).
# Обе раскладывают кнопки по одной в ряд (adjust(1)) из-за лимитов MAX
# на длину текста кнопки (подробный разбор — в handlers/menu.py).

def _list_keyboard():
    """
    Собирает клавиатуру со списком заметок пользователя.

    Метод add_callback возвращает сам KeyboardBuilder (flint-цепочка),
    поэтому можно вызывать add через точку сколько угодно раз.

    Тексты кнопок длиннее 10 символов (лимит для 2 кнопок в ряду),
    поэтому раскладываем их по одной в строку через adjust(1) — иначе
    MAX обрежет текст (баг «кривых кнопок», см. handlers/menu.py).
    """
    # Создаём пустой «холст» клавиатуры (объект KeyboardBuilder).
    kb = KeyboardBuilder()
    # Кнопка «Создать новую» с точным payload "note_create" — её примет
    # фильтр CallbackPayload("menu_notes", "note_create", ...) ниже.
    kb.add_callback(text="📝 Создать новую", payload="note_create")
    # Кнопка возврата в главное меню: универсальный payload "menu_main",
    # который обрабатывает роутер menu (подключённый в __init__ первым).
    kb.add_callback(text="← Назад в меню", payload="menu_main")
    # adjust(1) раскладывает все кнопки по ОДНОЙ в ряд — длинный текст
    # не будет обрезан MAX'ом (см. разбор бага кнопок в handlers/menu.py).
    return kb.adjust(1)


# Обрати внимание: у списка заметок НЕТ кнопок-заметок. Тот вариант списка,
# где каждая заметка — своя кнопка, собирается прямо в обработчике
# (см. handle_notes_menu), потому что количество заметок заранее
# неизвестно, и кнопки строятся в цикле.


def _back_to_list_keyboard(action_text, action_payload):
    """Маленький билдер с кнопкой действия и «назад к списку».

    text кнопки действия приходит из вызывающего кода и может быть
    длинным (например «📝 Создать ещё одну»), поэтому выстраиваем кнопки
    вертикально, чтобы ничего не обрезалось.
    """
    # Создаём «холст» клавиатуры для экрана с одним действием.
    kb = KeyboardBuilder()
    # Кнопка действия: текст и payload передаются из вызывающего кода
    # (например действие «Создать ещё одну» с payload "note_create").
    kb.add_callback(text=action_text, payload=action_payload)
    # Возврат к списку заметок — снова универсальный payload "menu_notes".
    kb.add_callback(text="← Назад к списку", payload="menu_notes")
    # По одной кнопке в ряд (вертикальный список) — текст не режется.
    return kb.adjust(1)


# ============================================================
# КОЛБЭКИ РАЗДЕЛА «ЗАМЕТКИ»
# ============================================================
# Принимаем точные payload'ы menu_notes, note_create и префиксы
# note_view_ / note_delete_ (далее в payload три индекса заметки).

# ОДИН обработчик на все кнопки раздела заметок: фильтр пропускает
# и точные значения, и любые строки с префиксом note_view_ / note_delete_.
#
# Префиксы в скобках — кортеж: фильтр понимает ВСЕ payload, начинающиеся
# на "note_view_" или "note_delete_", а какой именно индекс стоит после
# символа "_" уже разбирает сам обработчик через _parse_index().
#
# Почему именно префиксы, а не список всех значений? Число заметок не
# ограничено сверху, поэтому payload каждой кнопки уникален
# ("note_view_0", "note_view_1", ...). Перечислить их все заранее нельзя —
# а префиксный фильтр покрывает любые индексы автоматически.
@router.message_callback(
    CallbackPayload("menu_notes", "note_create", prefixes=("note_view_", "note_delete_"))
)
async def handle_notes_menu(update: MessageCallback, fsm_context) -> None:
    """Обрабатывает все кнопки раздела «Заметки»."""
    # Структура функции — большая каскадная конструкция if/elif по payload:
    #   menu_notes      -> показать список (или пустой экран при их отсутствии);
    #   note_create     -> инициализировать создание (перейти в FSM-ввод);
    #   note_view_<i>   -> показать одну заметку;
    #   note_delete_<i> -> удалить и перерисовать список.
    # Каждая ветка заканчивается return или последней отсылкой сообщения —
    # «проскок» в следующую ветку исключён.
    # Сам payload нажатой кнопки — уже обычная строка str
    # (фильтр CallbackPayload развернул его из Omittable).
    payload = update.payload
    # Определяем, кто нажал кнопку (у колбэка это настоящий нажавший).
    user_id = get_user_id(update)

    # Защитный барьер: дальше пропускаем только зарегистрированных,
    # одобренных и НЕ заблокированных пользователей. Если хотя бы одно
    # условие не совпадает — молча выходим (ничего не отправляем).
    if not db.user_exists(user_id) or not db.is_approved(user_id) or db.is_blocked(user_id):
        return
    # Этот же «входной барьер» стоит в меню, профиле и настройках, чтобы
    # все модули вели себя одинаково для посторонних и заблокированных.
    # Молчаливый return (без текста об ошибке) — тоже осознанный выбор:
    # не даём боту «раскрываться» перед случайными нажатиями чужих кнопок.

    # ============================================================
    # СПИСОК ЗАМЕТОК
    # ============================================================
    # Точный payload — пользователь нажал «Мои заметки» в главном меню.
    if payload == "menu_notes":
        # При входе в список отменяем незавершённое создание заметки.
        # fsm_context.clear() сбрасывает состояние и временные данные FSM
        # текущего пользователя (может быть мусор от прошлых попыток).
        await fsm_context.clear()

        # Тянем заметки пользователя из БД.
        # db.get_notes(user_id) возвращает список словарей: у каждого
        # элемента есть ключи index / title / content / time.
        notes = db.get_notes(user_id)

        if not notes:
            # Заметок нет — предлагаем создать первую.
            # Длинные тексты кнопок => по одной в ряд (adjust(1)).
            kb = KeyboardBuilder()
            kb.add_callback(text="📝 Создать первую заметку", payload="note_create")
            kb.add_callback(text="← Назад в меню", payload="menu_main")
            # Этот «пустой» экран собирается отдельно, чтобы юзер сразу
            # понял: заметок пока нет, но создать их легко одной кнопкой.
            # Тот же экран показывается и ПОСЛЕ удаления последней заметки
            # (см. ветку note_delete_), поэтому текст/кнопки тут дублируются
            # специально — пустые состояния выглядят одинаково.

            # callback_answer — короткая всплывающая подпись, которая
            # появляется над сообщением у нажавшего пользователя.
            await update.callback_answer(text="Заметки")
            # edit_message — заменяет содержимое исходного сообщения
            # (текст и/или клавиатуру) на новые.
            await update.edit_message(
                text="📝 У тебя пока нет заметок.\n\n"
                     "Нажми кнопку ниже, чтобы создать первую!",
                keyboard=kb.adjust(1).build(),
            )  # .build() превращает KeyboardBuilder в готовую структуру клавиатуры
            return  # раздел обработан — выходим из функции

        # Собираем текст списка заметок. len(notes) — общее количество.
        notes_text = f"📝 Твои заметки ({len(notes)}):\n\n"
        # Показывает только последние 10 заметок (срез списка notes[-10:]).
        display_notes = notes[-10:]
        # Выборка «последних 10» — защита от неподъёмно длинного сообщения:
        # заметок может быть сотни, весь список в одно сообщение не влезет.
        # Срез от конца списка ([-10:]) берёт самые свежие заметки.

        # Проходим по каждой отобранной заметке и добавляем её в текст.
        for note in display_notes:
            note_time = note.get("time", 0)  # Unix-время создания (int, секунды)
            # Форматируем дату как "дд.мм чч:мм" в локальной таймзоне;
            # если время не задано (0/False) — подставляем заглушку "Без даты".
            time_str = time.strftime("%d.%m %H:%M", time.localtime(note_time)) if note_time else "Без даты"
            title = note.get("title", "Без заголовка")  # заголовок заметки (str)
            notes_text += f"• {title} ({time_str})\n"   # один пункт списка на заметку
        # Итог — «меню» из пунктов, к которому ниже приклеятся кнопки.

        # Если заметок больше 10 — честно сообщаем, что остальные скрыты.
        if len(notes) > 10:
            notes_text += f"\n... и ещё {len(notes) - 10} заметок"
            # Точное число скрытых заметок показываем, чтобы не недоговаривать.

        kb = _list_keyboard()
        # Добавляем по кнопке на каждую из первых 5 заметок.
        # Каждая кнопка — это отдельный пункт списка, поэтому итоговая
        # клавиатура должна быть по ОДНОЙ кнопке в ряд (adjust(1)):
        # иначе KeyboardBuilder упакует 7 кнопок в ряд, а MAX обрежет
        # заголовки заметок до 3-5 символов (баг «текст кривой»).
        for note in display_notes[:5]:
            index = note.get("index", 0)  # числовой индекс заметки в хранилище
            title = note.get("title", "Без заголовка")[:30]  # обрезаем заголовок до 30 символов
            # Срез [:30] — предел длины заголовка-кнопки: длиннее всё равно
            # не поместится, а слишком длинная кнопка хуже читается.
            # Payload кнопки — "note_view_<index>": по префиксу note_view_
            # этот же обработчик поймёт, что нужно показать содержимое.
            kb.add_callback(text=f"📖 {title}", payload=f"note_view_{index}")

        # Показываем список: всплывающая подпись + редактирование сообщения.
        await update.callback_answer(text="Заметки")
        await update.edit_message(text=notes_text, keyboard=kb.adjust(1).build())
        # ОБЩИЙ ИТОГ ВЕТКИ: пользователь видит текст списка (до 10 заметок)
        # и клавиатуру: «Создать новую», «← Назад в меню» и до 5 кнопок-
        # заметок. Список и кнопки — это ДВА разных источника данных из
        # одного массива notes: текст берёт последние 10, кнопки — первые 5.

    # ============================================================
    # СОЗДАНИЕ НОВОЙ ЗАМЕТКИ
    # ============================================================
    # Точный payload "note_create" — нажата кнопка «Создать новую/первую».
    elif payload == "note_create":
        # Переводим в состояние «ждём заголовок». Временные данные чистим,
        # чтобы не оставался мусор от предыдущего создания.
        await fsm_context.clear()  # сбрасываем данные и состояние FSM
        # set_state ниже — ЯДРО механики: с этого момента maxo будет
        # пропускать сообщения этого пользователя в handle_notes_text.
        # set_state переводит пользователя в состояние NotesStates.wait_title.
        # Теперь любое его сообщение пройдёт фильтр StateFilter(NotesStates)
        # в обработчике handle_notes_text (ниже).
        await fsm_context.set_state(NotesStates.wait_title)

        kb = KeyboardBuilder()
        # Кнопка отмены — возвращает обратно в список заметок
        # (payload "menu_notes", обрабатывается веткой выше).
        kb.add_callback(text="← Отмена", payload="menu_notes")

        await update.callback_answer(text="Создание")
        await update.edit_message(
            text="📝 Создаём новую заметку!\n\n"
                 "Напиши заголовок заметки:",
            keyboard=kb.build(),  # кнопка одна — .build() без adjust(1)
        )
        # После этого сообщения у пользователя ЕСТЬ активное состояние
        # NotesStates.wait_title — следующее его текстовое сообщение
        # перехватит handle_notes_text, а не обычные обработчики команд.

    # ============================================================
    # ПРОСМОТР ЗАМЕТКИ
    # ============================================================
    # Колбэк с префиксом "note_view_" — пользователь нажал на заметку в списке.
    elif payload.startswith("note_view_"):
        # Вытаскиваем индекс из хвоста payload (после последнего "_"),
        # например "note_view_3" -> 3. Если распарсить не вышло — None.
        note_index = _parse_index(payload)
        if note_index is None:
            return  # повреждённый payload — молча выходим

        # Повторно тянем список из БД: всегда работаем со свежими данными.
        notes = db.get_notes(user_id)
        # Запрос к БД делается ЗАНОВО, а не переиспользуется прошлый —
        # между просмотром списка и нажатием могли добавиться/удалиться
        # заметки, поэтому индексы проверяем по актуальному состоянию.
        # Выход индекса за границы списка — заметки с таким индексом нет.
        if note_index < 0 or note_index >= len(notes):
            await update.callback_answer(text="❌")  # короткая всплывашка об ошибке
            await update.edit_message(text="❌ Заметка не найдена.")
            return

        # Достаём поля заметки из словаря (индекс в списке = позиция в хранилище).
        note = notes[note_index]
        title = note.get("title", "Без заголовка")
        content = note.get("content", "Пустая заметка")
        note_time = note.get("time", 0)  # та же Unix-метка времени, что и в списке
        # Более подробный формат даты для карточки заметки (с годом).
        # С годом — в отличие от короткого формата "дд.мм чч:мм" в списке:
        # подробная карточка предполагает, что пользователь хочет увидеть
        # полную информацию.
        time_str = time.strftime("%d.%m.%Y %H:%M", time.localtime(note_time)) if note_time else "Без даты"

        # Собираем текст карточки: заголовок + дата + содержимое.
        note_text = (
            f"📖 {title}\n"
            f"📅 {time_str}\n\n"
            f"{content}"
        )
        # Минималистичная карточка: три строки меты + само содержимое.
        # Никаких кнопок действий при просмотре — «удалить» вынесена
        # отдельно, чтобы случайное нажатие не удаляло заметку.

        kb = KeyboardBuilder()
        # Кнопка удаления: payload с префиксом note_delete_ и тем же индексом.
        kb.add_callback(text="🗑 Удалить", payload=f"note_delete_{note_index}")
        # Возврат к списку (обработается веткой "menu_notes" этого же хендлера).
        kb.add_callback(text="← Назад к списку", payload="menu_notes")
        # Пара кнопок «Удалить / Назад» — стандартный набор экрана просмотра:
        # первичное действие (удалить) и безопасный выход к списку.

        await update.callback_answer(text="Просмотр")
        await update.edit_message(text=note_text, keyboard=kb.build())

    # ============================================================
    # УДАЛЕНИЕ ЗАМЕТКИ
    # ============================================================
    # Колбэк с префиксом "note_delete_" — пользователь нажал «Удалить».
    # Индекс берётся из того же payload, что и при просмотре, но
    # обработка совсем другая: вместо показа текста — вызов delete_note.
    elif payload.startswith("note_delete_"):
        # Парсим индекс удаляемой заметки из payload (как и при просмотре).
        note_index = _parse_index(payload)
        if note_index is None:
            return  # не распарсилось — выходим

        # Удаляем заметку в БД. db.delete_note(...) возвращает bool:
        # True — удаление прошло, False — такой заметки нет / ошибка.
        success = db.delete_note(user_id, note_index)
        # Возврат bool позволяет не тянуть исключения из БД: достаточно
        # проверить True/False и выбрать соответствующий текст ответа.

        if not success:
            # Удалить не вышло — сообщаем об ошибке и выходим.
            await update.callback_answer(text="❌")
            await update.edit_message(text="❌ Ошибка при удалении заметки.")
            return

        await update.callback_answer(text="Удалено")
        await update.edit_message(text="✅ Заметка удалена!")

        # ВАЖНО: подтверждение и список — это ДВА разных сообщения.
        # edit_message уже «закрыл» старое сообщение (показал «удалено»),
        # а обновлённый список шлём новым через answer_text.

        # Показываем обновлённый список заметок НОВЫМ сообщением:
        # edit_message уже заменил старое сообщение, поэтому список
        # отправляем отдельно через answer_text.
        notes = db.get_notes(user_id)
        # Снова тянем свежий список: заметка удалена, и дальше важно,
        # осталась ли хоть одна заметка (это меняет и текст, и кнопки).
        if not notes:
            # Заметок больше нет — снова предлагаем создать первую.
            # adjust(1): длинные кнопки в столбик, чтобы текст не резался.
            kb = KeyboardBuilder()
            kb.add_callback(text="📝 Создать первую заметку", payload="note_create")
            kb.add_callback(text="← Назад в меню", payload="menu_main")
            await update.answer_text(
                "📝 У тебя больше нет заметок.",
                keyboard=kb.adjust(1).build(),
            )
        else:
            # Заметки остались — собираем текст обновлённого списка.
            notes_text = f"📝 Твои заметки ({len(notes)}):\n\n"
            for note in notes[-10:]:  # последние 10 заметок
                note_time = note.get("time", 0)
                time_str = time.strftime("%d.%m %H:%M", time.localtime(note_time)) if note_time else "Без даты"
                title = note.get("title", "Без заголовка")
                notes_text += f"• {title} ({time_str})\n"

            # Используем готовую клавиатуру списка (создать/назад в меню):
            # заметки-кнопки сюда не добавляем, т.к. это обновлённый список
            # после удаления — пользователь и так видел кнопки-заметки,
            # а сейчас важно подтвердить факт удаления, а не навигацию.
            kb = _list_keyboard()
            await update.answer_text(notes_text, keyboard=kb.build())


