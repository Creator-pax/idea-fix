# ============================================================
# ОБРАБОТЧИК КОМАНД /help И /menu — handlers/start.py
# ============================================================
# Этот файл отвечает за:
#   1. Команду /help — справку по командам бота;
#   2. Команду /menu — быстрый возврат в главное меню.
# (Сам /start обрабатывается в registration.py.)
#
# Несмотря на имя модуля (start), здесь НЕТ обработчика самого /start:
# он живёт в registration.py, потому что /start запускает анкету
# регистрации. В этом файле — только «служебные» команды:
# справка и быстрый вызов меню.
# ============================================================

# Router — класс maxo, из которого создаётся «роутер» — контейнер
# однотипных обработчиков. Каждый модуль проекта заводит свой Router.
from maxo import Router

# Command — фильтр для команд вида /<имя> (например /help, /menu).
# Фильтр пропускает в обработчик только подходящие сообщения.
from maxo.routing.filters import Command

# MessageCreated — тип апдейта «пришло новое сообщение в бот».
# Именно такой объект maxo передаёт в обработчик как аргумент update.
from maxo.types import MessageCreated

# database — самописный модуль работы с БД (см. database.py), который
# проксирует запросы во внешнюю базу. Импортируем сокращённо как db.
import database as db

# get_user_id — наша утилита безопасного извлечения user_id из апдейта.
from handlers.user_utils import get_user_id

# Создаём роутер с именем "start". Имя нужно в основном для отладки —
# по нему в логах видно, какой роутер обработал тот или иной апдейт.
router: Router = Router(name="start")
# На этом роутере зарегистрированы только два обработчика: /help и /menu.
# Оба — простые «быстрые» команды без состояний FSM и без клавиатур:
# нажал команду — получил ответ.

# ============================================================
# КОМАНДА /help
# ============================================================

# Регистрируем обработчик команды /help.
# Фильтр Command("help") пропускает сюда сообщения вида "/help"
# (с возможным текстом после команды). Вернёт update типа MessageCreated.
@router.message_created(Command("help"))
async def cmd_help(update: MessageCreated) -> None:
    """
    Показывает справку по командам бота.

    Фильтр Command("help") пропускает сюда только сообщения,
    начинающиеся с /help.
    """
    # Достаём числовой ID пользователя из апдейта (из отправителя сообщения).
    # Тип — int | None: если отправителя определить не удалось, будет None.
    user_id = get_user_id(update)

    # Если пользователь ещё не зарегистрирован (его нет в таблице users) —
    # показываем короткую подсказку и выходим.
    # db.user_exists(user_id) возвращает bool: True — запись в БД есть.
    if not db.user_exists(user_id):
        # answer_text — асинхронный фасад maxo: отправляет текст в тот же чат,
        # из которого пришёл апдейт (без клавиатуры — keyboard не передан).
        await update.answer_text(
            "📚 Справка\n\n"
            "Для начала напиши /start чтобы зарегистрироваться."
        )
        return  # досрочный выход: дальше в этой функции ничего не выполняется

    # Пользователь зарегистрирован — собираем текст справки.
    # help_text: строка (str), получаемая склейкой строковых литералов
    # внутри скобок (Python автоматически конкатенирует их в одну строку).
    # "\n\n" — перевод строки плюс пустая строка между смысловыми блоками.
    # Секции справки: команды (🔹), ИИ-функции (🤖) и прочее (📝) — чтобы
    # текст не превращался в одну бесконечную простыню. Каждая строка
    # начинается с маркера-эмодзи: он помогает глазу «зацепиться» за блок.
    help_text = (
        "📚 Справка по командам:\n\n"
        "🔹 /start — Главное меню\n"
        "🔹 /help — Эта справка\n"
        "🔹 /menu — Главное меню\n"
        "🔹 /myid — Узнать свой ID\n\n"
        "🤖 ИИ функции:\n"
        "• Задать вопрос по уроку\n"
        "• Составить расписание дня\n"
        "• Создать тест по теме\n"
        "• Помочь с домашкой\n\n"
        "📝 Другое:\n"
        "• Заметки — сохраняй мысли и идеи\n"
        "• Настройки — настраивай интерфейс под себя\n"
        "• Интерфейс — эмодзи, компактный вид, счётчики"
    )
    # Справка разбита на три смысловых блока (команды / ИИ / другое),
    # разделённых пустыми строками для читаемости в мессенджере.

    # Отправляем собранный help_text пользователю обычным сообщением.
    await update.answer_text(help_text)


# ============================================================
# КОМАНДА /menu
# ============================================================

# Обработчик команды /menu — быстрый возврат в главное меню
# без необходимости жать кнопки.
@router.message_created(Command("menu"))
async def cmd_menu(update: MessageCreated) -> None:
    """
    Показывает главное меню.

    Удобная команда для быстрого возврата в меню без нажатия кнопок.
    """
    # Получаем ID пользователя из апдейта (см. get_user_id в user_utils.py).
    user_id = get_user_id(update)

    # Проверяем два условия сразу: пользователь существует И одобрен
    # модератором (is_approved). Если хоть одно False — меню не показываем,
    # т.к. незарегистрированным пользователям делать там нечего.
    if not db.user_exists(user_id) or not db.is_approved(user_id):
        await update.answer_text("Сначала напиши /start чтобы зарегистрироваться.")
        return  # прерываем выполнение — меню не показываем

    # Импорт выполняется внутри функции (ленивый): так мы избегаем
    # циклического импорта, потому что menu.py сам импортирует другие
    # модули handlers. show_main_menu — асинхронная функция показа меню.
    from handlers.menu import show_main_menu
    # Ленивый импорт срабатывает только здесь, в момент вызова команды —
    # на этапе загрузки пакета handlers кольцевой зависимости не возникает.
    # Альтернатива (импорт вверху файла) приводила бы к ошибке цикла.

    # Передаём апдейт и ID — меню отправится в чат, откуда пришла команда.
    # Никаких дополнительных проверок здесь нет: они уже сделаны выше
    # (существует + одобрен), а текст/клавиатуру соберёт сама функция.
    await show_main_menu(update, user_id)