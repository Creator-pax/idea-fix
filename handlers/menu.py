# ============================================================
# ОБРАБОТЧИК ГЛАВНОГО МЕНЮ — handlers/menu.py
# ============================================================
# Этот файл отвечает за:
#   1. Показ главного меню после регистрации;
#   2. Навигацию по разделам бота;
#   3. Показ профиля пользователя.
#
# Здесь хорошо виден переход на maxo:
#   • клавиатура собирается через KeyboardBuilder;
#   • кнопки нажимаются -> приходит MessageCallback;
#   • отправка/редактирование — асинхронные фасады.
#
# ============================================================
# ВАЖНО ПРО РАСКЛАДКУ КНОПОК (разбор бага «текст в кнопках кривой»)
# ============================================================
# KeyboardBuilder.add_callback() -> add() раскладывает кнопки в РЯДЫ
# фиксированной ширины: по умолчанию 7 кнопок в ряд (max_width = 7).
#
# Проблема: у MAX есть жёсткие ограничения на длину видимого текста
# кнопки в зависимости от того, СКОЛЬКО кнопок стоит в одном ряду
# (см. docstring Button в maxo/src/maxo/types/button.py):
#     • 1 кнопка в ряду — до 20 символов
#     • 2 кнопки в ряду — до 10 символов
#     • 3 кнопки в ряду — до 5 символов
#     • 4 кнопки в ряду — до 3 символов
# Если кнопок в ряду больше — MAX молча ОБРЕЗАЕТ текст. Длинный русский
# текст и составные эмодзи (👨‍🏫, ← и т.п.) тогда «плывут» и режутся
# прямо посреди символа — отсюда и был баг «текст в кнопках кривой».
#
# Решение: меню — это вертикальный список ПУНКТОВ, где у каждой кнопки
# своя строка. Поэтому после добавления всех кнопок вызываем
# kb.adjust(1) — это перекладывает кнопки по ОДНОЙ в ряд (1 кнопка =
# лимит 20 символов, коротким меню-пунктам хватает с запасом).
#
# Если когда-нибудь понадобятся кнопки по 2+ в ряду (например,
# «Да/Нет»), помни про лимиты символов выше и не пиши в кнопку длиннее
# разрешённого — тогда текст снова начнёт обрезаться.
# ============================================================

# Router — класс для создания роутера (группы обработчиков меню).
from maxo import Router
# MessageCallback — нажатие кнопки; MessageCreated — новое сообщение в чат.
from maxo.types import MessageCallback, MessageCreated
