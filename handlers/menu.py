from maxo.utils.builders import KeyboardBuilder

# База данных (см. database.py): роли, профили, счётчики, заметки.
import database as db

# CallbackPayload — свой фильтр колбэков по значениям/префиксам payload.
from handlers.filters import CallbackPayload
# emoji — вставка эмодзи с пробелом (если включены); get_ui_prefs —
# чтение настроек интерфейса пользователя.
from handlers.prefs import emoji, get_ui_prefs
# RegistrationStates — группа состояний регистрации: нужна, чтобы НЕ
# сбрасывать процесс регистрации при возврате в меню.
from handlers.states import RegistrationStates
# get_user_id — безопасное получение ID пользователя из апдейта.
from handlers.user_utils import get_user_id

# Роутер меню. Его подключают ПЕРВЫМ в handlers/__init__.py, чтобы
# универсальный payload "menu_main" обрабатывался раньше всех остальных.
router: Router = Router(name="menu")

# Ниже файл делится на три логических блока:
#   1. КЛАВИАТУРА  — чистая функция-сборщик кнопок по роли пользователя;
#   2. ПОКАЗ МЕНЮ   — show_main_menu(); её же вызывают и другие модули;
#   3. ОБРАБОТЧИКИ  — нажатия кнопок с payload "menu_main" и "menu_profile".


# ============================================================
# КЛАВИАТУРА ГЛАВНОГО МЕНЮ
# ============================================================
# Функция ниже собирает клавиатуру для ГЛАВНОГО меню — то, что видит
# пользователь сразу после входа (или после любой кнопки «назад»).
# Отдельно, внутри обработчика профиля, собирается собственная маленькая
# клавиатура из одной кнопки «← Назад в меню». Итоговый вид клавиатуры —
# это просто список кнопок; текст приветствия строится в show_main_menu().
#
# КЛЮЧЕВАЯ ИДЕЯ: функция ЧИСТАЯ (не отправляет сообщения, не читает state) —
# она лишь возвращает KeyboardBuilder. Это позволяет переиспользовать её
# из любых мест (show_main_menu, регистрация, /menu) и легко тестировать.
# Такой подход — в духе разделения «сборка клавиатуры» и «отправка»: сборка
# не зависит от контекста апдейта, ей хватает одного user_id.

def get_main_menu_keyboard(user_id: int) -> KeyboardBuilder:
    """
    Создаёт клавиатуру главного меню в зависимости от роли пользователя.

    Возвращает KeyboardBuilder (можно достраивать). В конце получившийся
    объект надо преобразовать в нужный вид через .build() при передаче
    в keyboard= фасада.

    Args:
        user_id: Числовой ID пользователя

    Returns:
        KeyboardBuilder с кнопками меню.
    """
    # Достаём роль пользователя из БД.
    # db.get_user_field(user_id, "role") вернёт строку:
    # "student", "teacher", "moderator" или None/иное (если не задана).
    role = db.get_user_field(user_id, "role")
    # Роль определяет набор кнопок: ученикам — «Моя история», учителям и
    # модераторам — расширенный ИИ-инструментарий, модератору — панель.

    # ============================================================
    # ЧТО ТАКОЕ PAYLOAD И ПОЧЕМУ ОН ВАЖЕН
    # ============================================================
    # У каждого «раздела» меню своя кнопка с уникальным payload —
    # короткой строкой-идентификатором (например "ai_question").
    # Когда пользователь нажимает кнопку, MAX присылает боту колбэк
    # с этим payload, и его обрабатывает ровно тот роутер, чей
    # фильтр CallbackPayload(...) этот payload принимает.
    #
    # Payload — это НЕ текст кнопки: текст нужен пользователю,
    # payload нужен коду. Это важно, потому что текст можно менять
    # свободно (перевести, сократить), а payload менять нельзя —
    # иначе «сломаются» все фильтры (см. handlers/filters.py).
    # ============================================================

    # Базовые кнопки: видны всем ролям (ученик, учитель, модератор).
    # Формат кортежа: (текст кнопки, payload для колбэка).
    # Порядок в списке = порядок, в котором кнопки окажутся в меню.
    #
    # Кортежи здесь — это «таблица соответствия»: текст показывает юзеру,
    # payload понимает код. Поэтому текст можно менять свободно (переводить,
    # сокращать), а payload трогать нельзя — иначе сломаются фильтры.
    base = [
        ("❓ Вопрос по уроку", "ai_question"),      # ИИ: объяснение темы
        ("📅 Расписание дня", "ai_schedule"),       # ИИ: план на день
        ("📝 Создать тест", "ai_test"),             # ИИ: тест по теме
        ("📚 Помощь с домашкой", "ai_homework"),    # ИИ: решить домашку
        ("🛠 Документы и слайды", "doc_menu"),      # конструктор слайдов + правка файлов через ИИ
        ("📄 Файлы и медиа", "menu_media"),         # OCR, PDF, видео
        ("📋 Мои заметки", "menu_notes"),           # раздел заметок
        ("👤 Мой профиль", "menu_profile"),         # профиль пользователя
        ("⚙️ Настройки", "menu_settings"),          # раздел настроек
    ]
    # Восемь кнопок верхнего уровня: четыре ИИ-раздела ("ai_*"), раздел
    # документов ("doc_menu") и три внутренних раздела бота ("menu_*").
    # Фактическую «раскладку» по рядам
    # сделает adjust(1) ниже, чтобы длинный текст не обрезался MAX'ом.

    # Дополнительные кнопки ТОЛЬКО для учителей и модераторов:
    # специфические ИИ-инструменты, которых нет у учеников.
    teacher_extra = [
        ("📝 Набросок текста", "ai_presentation"),               # текст-черновик по теме
        ("📖 План урока по теме", "ai_topic"),             # план занятия
        ("👨‍🏫 История учеников", "ai_students_history"),   # логи обращений учеников
        ("📊 Логи ИИ", "menu_ai_logs"),                    # общие логи ИИ
    ]
    # Эти инструменты не имеют смысла для ученика (план урока, история
    # чужих обращений и т.п.), поэтому они добавляются только в ветке
    # проверки роли ниже — а не навечно в состав base.
    #
    # Итак, итоговое меню = base (всегда) + teacher_extra (учитель/модератор)
    # + «Моя история» (только ученик) + «Модерация» (только модератор).
    # Роль пользователя определяет эти «срезы» набора кнопок.

    # Создаём пустой KeyboardBuilder — это «холст», на который мы
    # будем добавлять кнопки. Методы add_callback/add_link и т.д.
    # возвращают тот же объект, поэтому их можно «цеплять» через точку
    # (flint-стиль) или вызывать по одной — как здесь.
    kb = KeyboardBuilder()

    # Модератор или учитель видят расширенный набор кнопок.
    # Условие: юзер модератор по БД ИЛИ его роль в ("teacher", "moderator").
    if db.is_moderator(user_id) or role in ("teacher", "moderator"):
        # Обрати внимание на логику: «или» здесь намеренное — роль могла
        # смениться в БД, но флаг модератора всё ещё выставлен. Проверяем
        # оба источника истины, чтобы кнопки не «потерялись» при рассинхроне.
        kb.add_callback(text="👨‍🏫 История учеников", payload="ai_students_history")
        kb.add_callback(text="📊 Логи ИИ", payload="menu_ai_logs")
        # Учителю и модератору доступны «История учеников» и «Логи ИИ» —
        # оба раздела про чужие данные, ученику они не нужны.
        if db.is_moderator(user_id):
            # Кнопку «Модерация» (приём/отклонение заявок) видит
            # ТОЛЬКО модератор — учитель к панели модерации не допускается.
            kb.add_callback(text="🛡 Модерация", payload="menu_moderation")
            # Второй if (а не "elif") здесь не случайность: модератор тоже
            # учитель-инструменты получил выше, а панель модерации — здесь.

    # Набор базовых кнопок меню.
    # Цикл распаковывает каждый кортеж (text, payload) в две переменные
    # и добавляет кнопку с данным текстом и данным payload.
    for text, payload in base:
        kb.add_callback(text=text, payload=payload)
    # Перебор здесь — это итерация по «таблице» кортежей; порядок кнопок
    # сохраняется ровно в том виде, в каком они заданы в списке base.
    # Распаковка кортежей — стандартный приём: вместо восьми одинаковых
    # вызовов add_callback один цикл по списку кортежей (text, payload).

    # Учителям/модераторам — дополнительные инструменты с ИИ.
    # Условие дублирует проверку выше (страховка от рассинхрона ролей):
    # даже если в БД роль «протухла», а флаг модератора ещё стоит — набор
    # кнопок всё равно соберётся полный.
    if role in ("teacher", "moderator") or db.is_moderator(user_id):
        for text, payload in teacher_extra:
            kb.add_callback(text=text, payload=payload)
    # Порядок добавления кнопок в билдер = порядок в готовой клавиатуре
    # (каждая кнопка ложится на последнее место), поэтому меню строится
    # заранее продуманной последовательностью: прежде всего модератор-
    # инструменты, потом базовая часть, потом преподавательские ИИ.

    # Ученикам — раздел «Моя история».
    # Условие обратное верхним: НЕ учитель И НЕ модератор => ученик.
    if role not in ("teacher", "moderator") and not db.is_moderator(user_id):
        kb.add_callback(text="📊 Моя история", payload="ai_my_history")
    # "ai_my_history" показывает школьнику его собственные обращения к ИИ,
    # учителю она не нужна — у него отдельный раздел «История учеников».

    # По одной кнопке в ряд: при нескольких кнопках в ряд MAX обрезает
    # длинный текст кнопки (рекомендуемые лимиты символов зависят от
    # количества кнопок в ряду), поэтому текст меню «плывёт»/режется.
    # adjust(1) раскладывает все кнопки вертикально и возвращает билдер.
    return kb.adjust(1)


# ============================================================
# ПОКАЗ ГЛАВНОГО МЕНЮ
# ============================================================

async def show_main_menu(update: MessageCreated | MessageCallback, user_id: int) -> None:
    """
    Показывает главное меню бота.

    Это служебная функция, которую вызывают из других модулей
    (например, после команды /start или после подтверждения).

    Внешний вид меню зависит от настроек интерфейса пользователя:
      • compact_mode — укороченное приветствие без счётчиков и роли;
      • show_emoji   — включение/отключение эмодзи в заголовке;
      • show_stats   — включение/отключение счётчиков ИИ и заметок.
    """
    # Получаем полный словарь пользователя из БД (или None, если записи нет).
    user = db.get_user(user_id)
    if not user:
        # Аномалия: пользователь не найден в БД. Просим перезапустить бота.
        await update.answer_text("Произошла ошибка. Напиши /start")
        return  # дальше работать не с чем — выходим

    # Читаем настройки интерфейса пользователя (см. handlers/prefs.py).
    # get_ui_prefs возвращает словарь {"show_emoji": bool, ...} с дефолтами.
    prefs = get_ui_prefs(user_id)
    show_emoji = prefs["show_emoji"]  # bool: показывать ли эмодзи
    compact    = prefs["compact_mode"]  # bool: компактный вид меню
    show_s     = prefs["show_stats"]    # bool: показывать ли счётчики
    # Все три флага приходят из БД (настройки интерфейса пользователя),
    # а если в БД значения ещё нет — подставляется дефолт из config.py.
    #
    # Настройки читаются ОДИН раз за вызов, а дальше по коду работаем
    # с распакованными локальными переменными (show_emoji/compact/show_s),
    # а не с самим словарём prefs — так строки ниже короче и читабельнее.

    # Имя пользователя: full_name если есть, иначе name, иначе заглушка.
    name = user.get("full_name") or user.get("name", "Пользователь")
    # Роль строкой: "student" / "teacher" / "moderator" / что-то ещё.
    role = user.get("role", "unknown")
    # Выражение a or b — «возьми первое непустое значение»: если full_name
    # пуст (None или пустая строка), в дело идёт name, иначе заглушка.

    # Словарь «роль -> эмодзи» для заголовка меню.
    # .get(role, "👤") возвращает дефолт для неизвестной роли.
    role_emoji = {
        "student": "📚",
        "teacher": "👨‍🏫",
        "moderator": "🛡",
    }.get(role, "👤")  # эмодзи-«иконка» текущей роли

    # Словарь «роль -> читаемое название» для текста меню.
    role_text = {
        "student": "Ученик",
        "teacher": "Учитель",
        "moderator": "Модератор",
    }.get(role, "Неизвестно")  # «перевод» техничесой роли в человеческий текст

    if compact:
        # Компактный режим: только имя и приглашение — без роли и счётчиков.
        text = (
            f"Привет, {name}!\n\n"
            "Выбери раздел:"
        )  # минимальный набор строк: привет + приглашение, без всего лишнего
        # Это «быстрый» режим: меньше текста — меньше прокрутки в чате,
        # пользователь сразу видит, что делать дальше. В этом режиме также
        # не читаются счётчики и роль — экономия обращений к БД.
    else:
        # Полный режим: приветствие + роль (+ счётчики, если включены).
        text = f"{emoji(show_emoji, '👋')} Привет, {name}!\n\n"
        text += f"{emoji(show_emoji, role_emoji)} Роль: {role_text}\n"
        # emoji() сам подставляет эмодзи с пробелом либо пустую строку —
        # один и тот же код работает и с эмодзи, и без них.
        if show_s:  # счётчики включены в настройках интерфейса
            ai_used  = db.get_ai_usage(user_id)        # запросов ИИ сегодня
            ai_limit = user.get("ai_daily_limit", 50)  # дневной лимит (дефолт 50)
            notes_count = len(db.get_notes(user_id))   # сколько у юзера заметок
            # Каждая строка-счётчик начинается со своего эмодзи (🤖/📝),
            # чтобы блок статистики визуально отделялся от приветствия.
            text += (
                f"{emoji(show_emoji, '🤖')} ИИ запросов сегодня: {ai_used}/{ai_limit}\n"
                f"{emoji(show_emoji, '📝')} Заметок: {notes_count}\n"
            )
        text += "\nВыбери раздел:"
        # Полный текст собирается КУСКАМИ через += : каждая часть (роль,
        # счётчики) добавляется по условию, и только приглашение — всегда.

    # Отправляем меню: текст + клавиатура, собранная через билдер.
    # KeyboardBuilder.build() формирует структуру клавиатуры, понятную MAX.
    await update.answer_text(
        text,
        keyboard=get_main_menu_keyboard(user_id).build(),
    )


# ============================================================
# НАЖАТИЯ КНОПОК ГЛАВНОГО МЕНЮ
# ============================================================
# Этот роутер принимает только «свои» payload'ы: menu_main и menu_profile.
# Всё остальное обрабатывают другие модули.
# Обрати внимание: внутри одна функция со словом elif — обе кнопки делят
# общий «вход» (проверка пользователя), поэтому их удобно держать вместе.
#
# Паттерн: сначала единый блок проверок (exists / approved / blocked),
# а уже потом — ветвление по payload. Это сводит дублирование проверок
# к минимуму и делает код модуля компактнее.

@router.message_callback(CallbackPayload("menu_main", "menu_profile"))
async def handle_menu_callbacks(update: MessageCallback, fsm_context) -> None:
    """
    Обрабатывает нажатия: «Назад в главное меню» и «Мой профиль».

    menu_main — это универсальная кнопка «назад», которая встречается
    ВО ВСЕХ разделах бота. Поэтому здесь же сбрасываем незавершённое
    состояние пользователя в FSM (кроме процесса регистрации).
    """
    payload = update.payload  # payload нажатой кнопки (строка str)
    user_id = get_user_id(update)  # ID нажавшего (у колбэка — из update.user)

    # Первые строки одинаковы для обеих веток ниже (menu_main и menu_profile):
    # это «единая дверь» в обработчик с проверками доступа.

    # Не зарегистрированный/не одобренный пользователь ничего тут не делает.
    if not db.user_exists(user_id) or not db.is_approved(user_id):
        return  # молча игнорируем чужие нажатия

    # Если аккаунт заблокирован — показываем уведомление о блокировке.
    if db.is_blocked(user_id):
        # callback_answer — всплывающая подпись «Блокировка».
        await update.callback_answer(text="Блокировка")
        # Заменяем содержимое сообщения на информацию о блокировке.
        await update.edit_message(
            "🚫 Твой аккаунт заблокирован модератором.\n"
            "Обратись к учителю или модератору за помощью."
        )
        return  # ветки меню/профиля для заблокированного не выполняются
        # Заблокированному пользователю показываем именно этот текст вместо
        # меню: он не должен попадать ни в какие разделы бота целиком.

    # ============================================================
    # ВОЗВРАТ В ГЛАВНОЕ МЕНЮ
    # ============================================================
    # Универсальный payload "menu_main" — нажата кнопка «← Назад в меню».
    if payload == "menu_main":
        # Проверяем, не идёт ли сейчас регистрация: если идёт, не трогаем
        # её состояния (иначе прервём ввод телефона/пароля и т.п.).
        state = await fsm_context.get_state()  # строка состояния FSM или None
        in_registration = _is_registration_state(state)  # True — юзер в регистрации
        # Проверка по префиксу строки состояния: именно так отличить шаги
        # анкеты от любых других состояний (заметок, ИИ, настроек).

        if not in_registration:
            # clear() сбрасывает любое незавершённое состояние
            # (заметки, ИИ, настройки).
            await fsm_context.clear()
            # Сброс нужен, чтобы «протухшие» состояния (например ввод текста
            # заметки) не мешали после возврата в меню и не «подхватывали»
            # случайные сообщения пользователя в следующих шагах бота.

        # Показываем главное меню (переиспользуемая функция из этого файла).
        await show_main_menu(update, user_id)

    # ============================================================
    # ПРОФИЛЬ
    # ============================================================
    # Payload "menu_profile" — нажата кнопка «Мой профиль».
    elif payload == "menu_profile":
        user = db.get_user(user_id)  # словарь с данными пользователя
        if not user:
            return  # профиль не найден — нечего показывать

        prefs = get_ui_prefs(user_id)  # настройки интерфейса (для эмодзи)
        show_emoji = prefs["show_emoji"]

        # Дальше — снова «запасные» get() с подписями: никакое отсутствующее
        # поле в карточке не должно выглядывать как None или Python-объект.
        # Поле, которого нет, превращается в человекочитаемую заглушку.

        # Вытаскиваем все поля профиля (с заглушками на случай отсутствия).
        name = user.get("full_name") or user.get("name", "Не указано")
        phone = user.get("phone", "Не указан")
        email = user.get("email", "")  # пустая строка => ниже станет "не указан"
        age = user.get("age", 0)       # 0 означает «не указан» (проверка ниже)
        school = user.get("school", "Не указана")
        class_name = user.get("class_name", "")  # класс есть только у учеников
        role = user.get("role", "unknown")
        # Заглушки в .get() — защита от отсутствующих ключей: если поля в БД
        # нет вообще, вместо None в тексте появится читаемая подпись.

        # Эмодзи и название роли — те же словари, что и в меню выше.
        role_emoji = {
            "student": "📚",
            "teacher": "👨‍🏫",
            "moderator": "🛡",
        }.get(role, "👤")  # иконка роли в карточке

        role_text = {
            "student": "Ученик",
            "teacher": "Учитель",
            "moderator": "Модератор",
        }.get(role, "Неизвестно")  # название роли в карточке

        # Собираем текст карточки профиля.
        # Выражение "email or 'не указан'": пустая строка считается False,
        # поэтому на её месте подставится заглушка.
        profile_text = (
            f"{emoji(show_emoji, '👤')} Твой профиль:\n\n"
            f"{emoji(show_emoji, role_emoji)} Роль: {role_text}\n"
            f"{emoji(show_emoji, '👤')} Имя: {name}\n"
            f"{emoji(show_emoji, '📱')} Телефон: {phone}\n"
            f"{emoji(show_emoji, '📧')} Email: {email or 'не указан'}\n"
        )  # базовая часть карточки общая для всех ролей
        # Карточка собирается так же «кусками», как и меню: сначала общая
        # часть (имя, телефон, email), а потом условные блоки (возраст,
        # школа/класс, расход ИИ) — каждый только при наличии данных.
        if age:  # age не 0/None — возраст указан, добавляем строку о нём
            profile_text += f"{emoji(show_emoji, '🎂')} Возраст: {age}\n"
        # Число 0 в age работает как False, поэтому для «не указанного»
        # возраста строку просто не добавляем.

        # Школа: показываем, если она указана; иначе подсказка о заявке.
        if school:
            profile_text += f"{emoji(show_emoji, '🏫')} Школа: {school}\n"
            if role == "student" and class_name:  # класс показываем только ученикам
                profile_text += f"{emoji(show_emoji, '📚')} Класс: {class_name}\n"
        else:
            # Школа не указана — подсказываем, как подать заявку через настройки.
            profile_text += (
                f"{emoji(show_emoji, '🏫')} Школа: не указана\n"
                "└ Настройки → «Школа и класс» → подать заявку\n"
            )  # короткая инструкция, куда нажать, чтобы заполнить школу

        # Если счётчики включены — добавляем в профиль расход ИИ за сегодня.
        if prefs["show_stats"]:
            ai_used  = db.get_ai_usage(user_id)        # запросов ИИ сегодня
            ai_limit = user.get("ai_daily_limit", 50)  # лимит (дефолт 50)
            profile_text += f"\n{emoji(show_emoji, '🤖')} ИИ запросов сегодня: {ai_used}/{ai_limit}"
        # Блок «ИИ запросов» появляется в карточке строго по той же
        # настройке show_stats, что и в меню — интерфейс остаётся цельным.

        # Клавиатура профиля — одна кнопка «назад в меню».
        back_kb = KeyboardBuilder()  # отдельный маленький билдер под карточку
        back_kb.add_callback(text="← Назад в меню", payload="menu_main")
        # Payload "menu_main" — снова универсальный: его перехватит ветка
        # "menu_main" этого же обработчика (см. выше).

        # Показываем карточку профиля, заменяя сообщение с клавиатурой.
        await update.callback_answer(text="Профиль")
        await update.edit_message(
            text=profile_text,
            keyboard=back_kb.build(),
        )


def _is_registration_state(state: str | None) -> bool:
    """
    Проверяет, относится ли текущее состояние FSM к регистрации.

    StateFilter/StatesGroup сериализуются в строки вида
    "<ИмяГруппы>:<имя_поля>". Начинается на "RegistrationStates:" —
    значит пользователь в регистрации.

    Args:
        state: Строка текущего состояния (или None, если состояния нет).

    Returns:
        True, если состояние относится к регистрации.
    """
    # Функция вынесена из обработчика отдельно: она относится к FSM-механике
    # maxo (строковое представление состояний) и может пригодиться и в
    # других местах проекта. Префиксный формат "Группа:поле" — конвенция maxo.
    if state is None:
        return False  # состояния нет — значит, это не регистрация

    # Сравниваем по префиксу "<ИмяКласса>:". startswith возвращает bool.
    # RegistrationStates.__name__ — это строка "RegistrationStates",
    # поэтому проверка эквивалентна state.startswith("RegistrationStates:").
    return state.startswith(RegistrationStates.__name__ + ":")


