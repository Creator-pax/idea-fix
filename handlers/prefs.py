# ============================================================
# НАСТРОЙКИ ИНТЕРФЕЙСА — handlers/prefs.py
# ============================================================
# Вспомогательные функции для настройки внешнего вида бота.
# Каждый пользователь может поменять эти параметры в
# «Настройки → Интерфейс»:
#   • show_emoji   — показывать ли эмодзи в меню и карточках;
#   • compact_mode — компактное меню (без развёрнутых подписей и счётчиков);
#   • show_stats   — показывать ли счётчики (ИИ, заметки) в главном меню.
#
# Файл — это скорее «библиотека» утилит, а не набор обработчиков: здесь
# нет @router.* декораторов. Его функции импортируются в menu.py, settings.py
# и другие модули, чтобы ВСЕ экраны бота согласованно учитывали настройки
# интерфейса пользователя.
#
# Ключевая идея: единая точка работы с настройками. Если бы каждый модуль
# читал настройки напрямую из БД, приходилось бы дублировать логику
# дефолтов и приведения к bool в десятке мест.
# ============================================================

# re — стандартный модуль регулярных выражений: нужен для вырезания
# эмодзи из текста кнопок и для схлопывания двойных пробелов.
import re

# config — модуль с настройками проекта (значения по умолчанию интерфейса
# лежат в константах config.UI_SHOW_EMOJI и т.д.).
import config

# database — модуль работы с БД: тут читаем и сохраняем настройки.
import database as db

# ============================================================
# НАБОР ФУНКЦИЙ ЭТОГО ФАЙЛА
# ============================================================
#   btn(show_emoji, text)  -> текст кнопки (эмодзи вырезаны/оставлены);
#   get_ui_prefs(user_id)  -> словарь всех трёх настроек с дефолтами;
#   set_ui_pref(user_id, key, value) -> сохранить одну настройку в БД;
#   emoji(show_emoji, symbol) -> "🤖 " или "" (для текста, не кнопок);
#   ui_label(show_emoji)   -> эмодзи "🖥" раздела настроек.
# Разделение btn()/emoji() важно: btn() обрабатывает целые строки (в т.ч.
# для клавиатур), а emoji() встраивается в середину уже готовых фраз.

# Ключи настроек интерфейса, которые хранятся в таблице users.
# Порядок важен: используется в настройках для проверки/смены значений.
UI_KEYS = ("show_emoji", "compact_mode", "show_stats")
# Это «белый список» ключей: set_ui_pref не примет ничего, чего нет в нём,
# а get_ui_prefs гарантированно вернёт все три ключа со значениями.
# ВАЖНО: ключи используются и как имена столбцов БД, и как ключи словаря
# настроек — поэтому менять их надо согласованно с database.py.

# Регулярка для вырезания эмодзи из текста кнопок, когда пользователь
# выключил их в интерфейсе. Покрывает основные блоки Unicode:
#   • 1F000–1FAFF — основная масса эмодзи (смайлы, жесты, еда, флаги и т.д.);
#   • 2600–27BF   — символы (🔥 ⭐ ♻  и т.п.);
#   • 2190–21FF, 2300–23FF — стрелки и технические символы (← ⏭ ⌚);
#   • 2B00–2BFF   — прочие символы (⭐ и т.п.);
#   • 200D (ZWJ)  — соединитель составных эмодзи (👨‍🏫 = 👨+ZWJ+🏫);
#   • FE0F        — вариативный селектор (rendering variation).
# Символы кодовых точек записаны в escaped-виде (\UXXXXXXXX), чтобы их можно
# было хранить в исходнике независимо от кодировки файла.
_EMOJI_RE = re.compile(
    "[\U0000200D\U0000FE0F"
    "\U00002190-\U000021FF"
    "\U00002300-\U000023FF"
    "\U00002600-\U000027BF"
    "\U00002B00-\U00002BFF"
    "\U0001F000-\U0001FAFF]+"
)
# Точки выше перечислены по возрастанию кодов: сначала соединители/селекторы
# (200D, FE0F — без них разваливаются составные эмодзи), потом символы и
# технические знаки, и в конце — основные блоки эмодзи. Всё это в одной
# строке-классе [...] , поэтому re.sub заменяет эмодзи любой длины.


def btn(show_emoji: bool, text: str) -> str:
    """
    Готовый текст для КНОПКИ с учётом настройки эмодзи.

    Если эмодзи выключены — вырезает их из текста и убирает лишние
    пробелы. Это единая точка, через которую должны проходить ВСЕ тексты
    кнопок меню, чтобы переключатель «Эмодзи» реально работал везде.

    Args:
        show_emoji: Включены ли эмодзи у пользователя.
        text: Исходный текст кнопки (может содержать эмодзи).

    Returns:
        Текст для кнопки (с эмодзи или без них).
    """
    # Этот метод отличается от emoji(): btn() возвращает ПОЛНЫЙ текст
    # кнопки (с эмодзи в начале или без них), а emoji() — только сам
    # символ с пробелом для встраивания в середину предложений.
    if show_emoji:
        return text  # эмодзи включены — отдаём текст как есть, без изменений
        # Ранний выход (early return) упрощает дальнейший код: если эмодзи
        # включены, до регулярных выражений дело просто не доходит.

    # Эмодзи выключены: вырезаем все найденные эмодзи из строки.
    # re.sub(pattern, replacement, string) — заменяет все совпадения на "".
    cleaned = _EMOJI_RE.sub("", text)
    # После вырезания могли остаться сдвоенные пробелы ("📝 Набросок" ->
    # " Набросок"). r"\s{2,}" — 2 и более пробелов подряд -> один пробел,
    # затем .strip() убирает пробелы по краям строки.
    # Итог: например "📝 Набросок текста" -> "Набросок текста", а кнопка
    # становится короткой и аккуратной.
    return re.sub(r"\s{2,}", " ", cleaned).strip()
    # Два шага подряд: 1) «очистка от эмодзи», 2) «причёсывание пробелами».
    # Сначала убираем эмодзи, потом склеиваем двойные пробелы — если делать
    # наоборот, порядок не изменится, но этот вариант читается понятнее.


def get_ui_prefs(user_id: int) -> dict:
    """
    Возвращает настройки интерфейса пользователя.

    Значения по умолчанию берутся из config.py, поэтому даже если
    у пользователя ещё ничего не сохранено — будет разумный дефолт.

    Args:
        user_id: Числовой ID пользователя.

    Returns:
        Словарь {"show_emoji": bool, "compact_mode": bool, "show_stats": bool}.
    """
    # Достаём запись пользователя из БД. Если юзера нет — get_user вернёт
    # None, поэтому подстраховываемся через or {} (пустой словарь).
    user = db.get_user(user_id) or {}
    # Собираем словарь из трёх настроек. Инструкция:
    #   user.get(key, дефолт) — значение из БД или дефолт из config,
    #   bool(...) — приводим к True/False (в БД хранится 0 или 1).
    #
    # Пользователь может ещё ни разу не открывать настройки — тогда в БД
    # столбцов с его значениями нет, и на каждый ключ вернётся дефолт из
    # config.py. Это важное свойство: интерфейс работает «с первого дня».
    return {
        "show_emoji": bool(user.get("show_emoji", config.UI_SHOW_EMOJI)),
        "compact_mode": bool(user.get("compact_mode", config.UI_COMPACT_MODE)),
        "show_stats": bool(user.get("show_stats", config.UI_SHOW_STATS)),
    }
    # КЛЮЧИ словаря совпадают с UI_KEYS, поэтому вызывающий код может
    # полагаться на наличие всех трёх ключей сразу (без проверки на None).


def set_ui_pref(user_id: int, key: str, value) -> None:
    """
    Сохраняет одну настройку интерфейса.

    Args:
        user_id: Числовой ID пользователя.
        key: Одна из UI_KEYS ("show_emoji"/"compact_mode"/"show_stats").
        value: Новое значение (любое правдивое/ложное).
    """
    # Пишет значение ТОЛЬКО для существующего ключа интерфейса.
    if key in UI_KEYS:  # принимаем только известные ключи настроек
        db.set_user_field(user_id, key, 1 if value else 0)
    # Сторонние ключи (например опечатки в вызовах) молча игнорируются,
    # чтобы случайно не записать в БД мусорный столбец.
    # bool() покрывает и числа (0/1), и строки ("да"/""), и None: правило
    # «правдивость -> 1, ложность -> 0» едино для всех типов значения.


def emoji(show_emoji: bool, symbol: str) -> str:
    """
    Возвращает эмодзи с пробелом, если они включены, иначе пустую строку.

    Позволяет строить строки вида "🤖 ИИ запросов" или "ИИ запросов"
    без дублирования кода в каждом модуле.

    Args:
        show_emoji: Включены ли эмодзи у пользователя.
        symbol: Сам эмодзи (например "🤖").

    Returns:
        "🤖 " если включены, иначе "".
    """
    # Результат всегда заканчивается пробелом: эмодзи вставляются в
    # середину текста ("🤖 ИИ запросов"), и пробел нужен для разделения.
    # Если эмодзи выключены — возвращаем пустую строку, и предложение
    # начинается сразу с нужного слова, без лишних пробелов в начале.
    # f-string: "{symbol} " — эмодзи с пробелом (чтобы слово не прилипало
    # к эмодзи). Если эмодзи выключены — возвращаем пустую строку "".
    return f"{symbol} " if show_emoji else ""


def ui_label(show_emoji: bool):
    """Возвращает эмодзи главного меню настроек интерфейса."""
    # ui_label — обёртка над emoji: в настройках везде используется
    # эмодзи "🖥", и чтобы не дублировать его в каждом модуле — вынесли сюда.
    # Если пользователь выключил эмодзи, вернётся пустая строка — такой же
    # механизм, как во всех остальных местах интерфейса.
    return emoji(show_emoji, "🖥")
    # Возвращаемый тип — str. Тип-аннотации намеренно нет: это самый простой
    # способ гарантировать одинарный источник «иконки» настроек.