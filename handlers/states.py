# ============================================================
# FSM — СОСТОЯНИЯ БОТА — handlers/states.py
# ============================================================
# В этой библиотеке maxo (как и в aiogram) состояния пользователя
# описываются через FSM — «конечный автомат состояний»
# (Finite State Machine). Это штатный механизм maxo, он пришёл на
# смену самодельному state_manager.py (словари user_states /
# user_temp_data), который мы использовали с maxgram.
#
# Чем FSM maxo удобнее самодельного менеджера:
#   • состояние хранится в отдельном хранилище (по умолчанию
#     MemoryStorage) и автоматически «привязано» к конкретному
#     пользователю и чату — поэтому не нужно вручную хранить
#     словарь {user_id: state};
#   • вместе с состоянием можно хранить любые временные данные
#     (методом fsm_context.update_data(...)), что заменяет
#     user_temp_data — например, собрать телефон/пароль/имя
#     между шагами регистрации;
#   • фильтрация сообщений по состоянию делается декларативно
#     через StateFilter(...) прямо в декораторе обработчика.
#
# Ключевые понятия:
#   State       — одно конкретное состояние (например,
#                 «ожидаем ввод телефона ученика»).
#   StatesGroup — класс-контейнер, объединяющий несколько связных
#                 State в один смысловой блок. Поля класса,
#                 которым присвоен State(), и есть состояния.
#
# ВАЖНО про имена состояний: get_state() в maxo возвращает строку
# вида "<Класс>:<поле>" (например "RegistrationStates:wait_phone_student").
# Для удобства фильтрации мы почти всегда используем StateFilter(...),
# который принимает сами объекты State/StatesGroup и сам сравнивает
# строки — вручную сравнивать строки состояний не нужно.
# ============================================================

# Импортируем два ключевых класса FSM из библиотеки maxo:
#   State       — одно состояние;
#   StatesGroup — группа (контейнер) связанных состояний.
from maxo.fsm import State, StatesGroup


# ============================================================
# СОСТОЯНИЯ РЕГИСТРАЦИИ
# ============================================================
# Последовательность шагов регистрации разная у ученика и учителя:
#   ученик:  телефон → пароль → имя → класс → школа → email → возраст
#   учитель: телефон → пароль → имя → школа → email → возраст
# Email и возраст — опциональные шаги (можно пропустить кнопкой).
# Поэтому у каждого шага — отдельное состояние.
class RegistrationStates(StatesGroup):
    # --- ученик ---
    # Каждое поле класса, которому присвоена State(), — это отдельное
    # состояние. Порядок объявления задаёт внутреннюю логику шагов.
    # Строка состояния строится как "<ИмяКласса>:<имя_поля>".
    wait_phone_student = State()      # ждём номер телефона
    wait_password_student = State()   # ждём пароль
    wait_name_student = State()       # ждём имя
    wait_class_student = State()      # ждём класс
    wait_school_student = State()     # ждём школу
    wait_email_student = State()      # ждём email (опционально)
    wait_age_student = State()        # ждём возраст (опционально, финал)
    # «Финал» — после этого шага регистрация завершается и бот строит меню.
    # Отдельные состояния шагов позволяют обрабатывать каждый ответ своим
    # кодом (валидация телефона != валидации возраста и т.п.).

    # --- учитель ---
    # У учителя НЕТ шага «класс» (класс есть только у ученика), поэтому
    # состояний на одно меньше, чем у ученика.
    wait_phone_teacher = State()      # ждём номер телефона
    wait_password_teacher = State()   # ждём пароль
    wait_name_teacher = State()       # ждём имя
    wait_school_teacher = State()     # ждём школу
    wait_email_teacher = State()      # ждём email (опционально)
    wait_age_teacher = State()        # ждём возраст (опционально, финал)


# ============================================================
# СОСТОЯНИЯ РАЗДЕЛА ИИ
# ============================================================
# Когда пользователь нажал «Вопрос по уроку», «Тест» и т.п., бот
# ждёт от него текстовое сообщение. Сам режим (question/test/...)
# хранится во временных данных FSM (fsm_context.update_data(mode=...)),
# а состояние wait_question просто говорит «мы чего-то ждём от ИИ».
class AiStates(StatesGroup):
    wait_question = State()  # ждём текстовый запрос пользователя к ИИ (любой режим)
    # Режим здесь один на все ИИ-функции: ветвление (вопрос/тест/расписание)
    # происходит по значению mode из временных данных, а не по состоянию.


# ============================================================
# СОСТОЯНИЯ ЭКСПОРТА В ФАЙЛ
# ============================================================
# В мастере «Сохранить в файл» (handlers/export.py) почти всё решается
# кнопками-колбэками, но приём фотографий — это обычные сообщения-картинки,
# поэтому им нужно состояние: пока оно активно, каждое пришедшее фото
# добавляется в документ, а завершение — кнопкой «✅ Готово».
class ExportStates(StatesGroup):
    wait_photos = State()  # ждём фотографии для вставки в документ
    wait_title = State()   # ждём СВОЁ название документа/презентации


# ============================================================
# СОСТОЯНИЯ ЗАМЕТОК
# ============================================================
# Создание заметки идёт в два шага: сначала заголовок, потом текст.
class NotesStates(StatesGroup):
    wait_title = State()     # ждём заголовок заметки
    wait_content = State()   # ждём содержимое заметки
    # Заголовок, принятый в wait_title, кладётся во временные данные
    # (fsm_context.update_data(note_title=...)), а переход в wait_content
    # означает «следующий текст — это содержимое».


# ============================================================
# СОСТОЯНИЯ НАСТРОЕК
# ============================================================
# Используется для ввода интересующих тем для ИИ и для смены
# школы/класса (заявка на вступление в новую школу).
class SettingsStates(StatesGroup):
    wait_topics = State()    # ждём текст с темами

    # --- смена школы/класса ---
    # Заявка на вступление собирается в два шага: сначала школа,
    # потом класс (для ученика). Выход из школы требует подтверждения.
    wait_join_school = State()    # ждём название школы, в которую хотим вступить
    wait_join_class = State()     # ждём класс (после ввода школы)
    wait_leave_confirm = State()  # ждём подтверждение выхода из школы

    # --- лимиты ИИ для учеников (учитель/модератор) ---
    # Для смены дневного лимита ученика учителю нужно ввести два значения:
    # user_id ученика и само новое число — поэтому два состояния.
    wait_limit_uid = State()      # ждём user_id ученика (или передан из кнопки)
    wait_limit_value = State()    # ждём новое значение лимита

    # --- редактирование персональных данных ---
    # Каждое поле редактируется отдельной веткой настроек, поэтому
    # под каждое поле — своё состояние ожидания нового значения.
    wait_edit_name = State()      # ждём новое имя
    wait_edit_phone = State()     # ждём новый телефон
    wait_edit_email = State()     # ждём новый email
    wait_edit_age = State()       # ждём новый возраст
    wait_edit_password = State()  # ждём новый пароль


# ============================================================
# СОСТОЯНИЯ РАЗДЕЛА «ФАЙЛЫ И МЕДИА»
# ============================================================
# Пользователь выбрал режим обработки медиа и мы ждём от него
# вложение (фото, PDF или видео).
class MediaStates(StatesGroup):
    wait_photo = State()            # ждём фото (OCR)
    wait_pdf = State()              # ждём PDF-файл
    wait_video_audio = State()      # ждём видео (распознавание речи)
    wait_video_keyframes = State()  # ждём видео (ключевые моменты)
    # Каждый тип вложения — своё состояние, потому что обработка
    # отличается (OCR для картинок, разбор PDF, речь/раскадровка видео).


# ============================================================
# СОСТОЯНИЯ РАЗДЕЛА «ДОКУМЕНТЫ И СЛАЙДЫ»
# ============================================================
# Этот раздел (handlers/documents.py) отвечает за две группы функций:
#   1) РЕДАКТИРОВАНИЕ документов через ИИ — пользователь присылает
#      .docx/.rtf/.pdf/.pptx файл, бот извлекает из него текст,
#      отправляет текст ИИ на редактирование по инструкции юзера,
#      собирает документ заново и отправляет обратно;
#   2) МИНИ-КОНСТРУКТОР слайдов — пользователь по шагам вводит заголовок,
#      текст, число слайдов, и бот собирает готовую презентацию .pptx.
#
# FSM нужен, потому что в обеих функциях есть ШАГИ ОЖИДАНИЯ ВВОДА:
#   • приём файла/текста от пользователя — обычные сообщения;
#   • несколько последовательных запросов текста (заголовок → текст);
#   • ожидание инструкции «что исправить в документе».
# Все эти «ожидания» — отдельные состояния StatesGroup ниже.
class DocStates(StatesGroup):
    # ─── мини-конструктор слайдов ───
    # Шаг 1: ждём заголовок презентации (текстом).
    wait_slide_title = State()
    # Шаг 2: ждём основной текст для слайдов (или "авто" — ИИ сгенерит).
    wait_slide_text = State()
    # Шаг 3: ждём число слайдов (1..10 или "авто").
    wait_slide_count = State()
    # Шаг 4: ждём название для файла / выбор оформления (кнопки).
    wait_slide_style = State()

    # ─── редактирование документа через ИИ ───
    # Ждём сам файл документа (может прийти ДО выбора режима —
    # пользователь просто шлёт файл, и бот спрашивает «что сделать»).
    wait_doc_file = State()
    # Ждём инструкцию от пользователя: «что исправить / дополнить».
    wait_edit_instruction = State()
    # Ждём подтверждение количества правок (кнопки) — перед сборкой.
    wait_edit_confirm = State()


# ============================================================
# СОСТОЯНИЯ МОДЕРАТОРА
# ============================================================
# Используются при работе с инструментами модерации прямо в чате:
# блокировка пользователя, смена лимита ИИ, рассылка сообщений.
class ModerationStates(StatesGroup):
    wait_uid = State()        # ждём user_id (для блокировки / смены лимита)
    wait_limit = State()      # ждём новое значение дневного лимита ИИ
    wait_broadcast = State()  # ждём текст рассылки для всех пользователей