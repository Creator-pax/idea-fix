# ============================================================
# СБОРКА ОБРАБОТЧИКОВ — handlers/__init__.py
# ============================================================
# В maxo каждый модуль обработчиков — это отдельный Router.
# Здесь мы собираем все Router'ы в общий Dispatcher (dp)
# с помощью dp.include_router(...).
#
# ВАЖНОЕ ОТЛИЧИЕ от старого maxgram-кода:
#   раньше @bot.command / @bot.on цеплялось к ОДНОМУ объекту bot.
#   Теперь каждая группа обработчиков регистрируется на своём роутере,
#   а роутеры вешаются на диспетчер.
#
# ВАЖНО ПРО ПОРЯДОК:
#   Первый роутер, чей фильтр совпал с апдейтом, «забирает» его себе
#   и останавливает поиск. Поэтому menu подключаем ПЕРВЫМ:
#   универсальная кнопка «← Назад в меню» (payload "menu_main")
#   должна обрабатываться раньше всех остальных кнопок.
#   Остальные роутеры фильтруют свои payload'ы взаимоисключающе,
#   поэтому их порядок между собой не
#
# Этот файл — «точка входа» пакета handlers: достаточно один раз
# импортировать handlers где-то в боте, и все роутеры автоматически
# окажутся подключены к диспетчеру. Сам бот (bot_instance) при этом
# импортирует этот пакет, чтобы запустить обработчики.
# ============================================================

# Импортируем уже созданный в модуле bot_instance объект Dispatcher (dp).
# Это общий «диспетчер», на который будут «вешаться» все роутеры проекта.
from bot_instance import dp

# Импортируем модули-обработчики. Этот файл является точкой сборки пакета
# handlers: каждый модуль при импорте создаёт свой Router и регистрирует
# на нём обработчики через декораторы @router.*.
from handlers import ai            # ИИ-функции (вопросы, тесты, расписания и т.п.)
from handlers import documents     # документы: мини-конструктор слайдов + редактирование файлов через ИИ
from handlers import export        # сохранение ответов ИИ в файлы (PDF/Word/RTF/PPTX)
from handlers import media         # обработка файлов и медиа (OCR, PDF, видео)
from handlers import menu          # главное меню и навигация
from handlers import moderation    # панель модератора (заявки, блокировки и т.п.)
from handlers import notes         # заметки пользователя
from handlers import registration  # регистрация (/start, шаги анкеты)
from handlers import settings      # настройки пользователя
from handlers import start         # команды /help и /menu
# Внимание: порядок импортов НЕ влияет на маршрутизацию апдейтов — её
# задаёт порядок вызовов include_router ниже. Импорт лишь загружает модули.

# Подключаем роутеры к диспетчеру в нужном порядке (см. комментарий выше).
# dp.include_router(<router>) регистрирует обработчики роутера в диспетчере.
# Последовательность вызовов задаёт приоритет поиска подходящего обработчика.
dp.include_router(menu.router)          # menu первым — перехватывает кнопку "menu_main"
dp.include_router(start.router)         # команды /help и /menu
dp.include_router(registration.router)  # регистрация: /start и ввод анкеты
dp.include_router(notes.router)         # раздел заметок (payload'ы note_*)
dp.include_router(ai.router)            # ИИ-раздел (вопросы, тесты)
dp.include_router(documents.router)     # документы: конструктор слайдов + редактирование файлов через ИИ
dp.include_router(export.router)        # сохранение ответов ИИ в файлы
dp.include_router(settings.router)      # раздел настроек
dp.include_router(moderation.router)    # инструменты модератора
dp.include_router(media.router)         # файлы и медиа
# Итоговый приоритет: сначала «навигация» (menu), потом служебные команды
# (start), анкета (registration), заметки, ИИ, настройки, модерация и медиа.
# Если какой-то обработчик не нашли — диспетчер просто ничего не сделает.

# Экспортируем модули для удобства.
# Список __all__ определяет имена, доступные при `from handlers import *`,
# и даёт внешнему коду явный перечень доступных подмодулей-обработчиков.
__all__ = [
    "ai",            # ИИ-обработчики
    "documents",     # документы и слайды
    "export",        # сохранение ответов ИИ в файлы
    "media",         # обработчики медиа
    "menu",          # меню и навигация
    "moderation",    # модерация
    "notes",         # заметки
    "registration",  # регистрация
    "settings",      # настройки
    "start",         # команды /help, /menu
]