# ============================================================
# СВОИ ФИЛЬТРЫ — handlers/filters.py
# ============================================================
# В maxo обработчики кнопок (колбэков) принято «навешивать» на
# конкретные payload'ы с помощью фильтров. Фильтр — это объект с
# единственным асинхронным методом __call__(update, ctx), который
# возвращает True (обрабатываем этот апдейт здесь) или False (не наш).
#
# maxo поставляется с готовыми фильтрами:
#   • Command(...) / CommandStart() — для команд вида /start;
#   • StateFilter(...)              — для фильтрации по состоянию FSM;
#   • Payload / CallbackData        — для разбора структурированных
#                                     колбэков (про пакет-упаковку).
# Но в нашем боте payload'ы — это простые строки с префиксами
# (например "menu_notes", "note_view_3", "mod_approve_123456").
# Поэтому мы напишем один маленький свой фильтр CallbackPayload,
# который понимает и точные значения, и строки по префиксу.
#
# Это отличный пример, как расширять maxo: любой свой фильтр должен
# наследовать maxo.routing.filters.BaseFilter (или просто реализовать
# интерфейс Filter) и определять async __call__(update, ctx).
#
# ИТОГ: фильтр — это «пропускная рамка» перед обработчиком. Если результат
# __call__ = True, maxo передаёт апдейт в обработчик, если False — ищет
# следующий подходящий роутер. Всю «черновую» маршрутизацию по строкам
# payload приятно держать здесь, в одном классе.
# ============================================================

# Iterable — тип из стандартной библиотеки (collections.abc): означает,
# что prefixes — это любой «перечисляемый» объект: список, кортеж,
# генератор и т.п. Это только аннотация типа, на работу не влияет.
from collections.abc import Iterable

# Ctx — контекст обработчика maxo: хранит FSM-контекст, данные апдейта
# и прочее служебное окружение. Передаётся в __call__ вторым аргументом.
from maxo import Ctx

# is_defined — функция проверки «значение вообще задано». Нужна для полей
# типа Omittable[T]: такое поле может отсутствовать, и тогда прямое
# обращение к нему вернёт None (или вызовет ошибку при нетипизированном доступе).
from maxo.omit import is_defined

# BaseFilter — базовый класс для создания собственных фильтров maxo.
# Наследуясь от него, наш фильтр корректно интегрируется в систему роутинга.
from maxo.routing.filters import BaseFilter

# MessageCallback — тип апдейта «нажата кнопка (колбэк)»: содержит user,
# payload, callback и исходное сообщение с клавиатурой.
from maxo.types import MessageCallback


# Параметр дженерика BaseFilter[MessageCallback] — тип апдейта, с которым
# работает фильтр (именно колбэки кнопок). Даёт автодополнение и типизацию.
class CallbackPayload(BaseFilter[MessageCallback]):
    """
    Фильтр колбэков по значению payload.

    Примеры использования в декораторе обработчика:

        @router.message_callback(
            CallbackPayload("menu_notes", "note_create")  # точные значения
        )
        async def handle(ctx: ...): ...

        @router.message_callback(
            CallbackPayload(prefixes=("note_view_", "note_delete_"))  # по префиксу
        )
        async def handle(ctx: ...): ...

    Args:
        values: Точные payload'ы, которые должен принимать фильтр.
        prefixes: Префиксы, по которым payload'ы принимаются через startswith.
    """

    # __slots__ — ограничивает набор атрибутов экземпляра класса. Экономит
    # память и ускоряет доступ к полям, а заодно не даёт случайно
    # «приписать» объекту фильтра посторонние атрибуты.
    __slots__ = ("values", "prefixes")

    # Конструктор фильтра: принимает произвольное число точных значений
    # (*values) и необязательный перечень префиксов (prefixes).
    def __init__(
        self,
        *values: str,  # точные payload'ы — одна и более строк
        prefixes: Iterable[str] = (),  # префиксы для startswith; по умолчанию пусто
    ) -> None:
        # Храним значения в виде неизменяемых кортежей (tuple) — так
        # надёжнее, чем список: никто случайно не изменит фильтр извне.
        self.values = tuple(values)      # tuple[str]: точные значения payload
        self.prefixes = tuple(prefixes)  # tuple[str]: префиксы для сравнения
        # Приведение к tuple делает фильтр «замороженным»: даже если
        # вызывающий код передал список, дальше он хранится как кортеж.

    # Главный метод фильтра: maxo вызывает его для каждого колбэка.
    # Возвращает True (наш апдейт — обрабатываем) или False (не наш —
    # поиск продолжается по другим фильтрам/роутерам).
    async def __call__(self, update: MessageCallback, ctx: Ctx) -> bool:
        # Поле payload у MessageCallback — типа Omittable[str], т.е. его
        # может просто не быть (кнопка без данных). Прежде чем работать
        # со значением, проверяем через is_defined, что оно задано.
        if not is_defined(update.payload):
            return False  # payload отсутствует — такой колбэк нам не подходит

        payload = update.payload  # здесь уже обычная строка (тип str)

        # Точное совпадение с одним из перечисленных значений.
        # Оператор in проверяет, равен ли payload хотя бы одному из values
        # (например кнопка "menu_notes" -> True).
        if payload in self.values:
            return True  # точное совпадение — фильтр сработал

        # Либо совпадение префикса (для payload с числами и т.п.).
        # any(...) возвращает True, если payload начинается хотя бы с одного
        # префикса (например "note_view_3".startswith("note_view_") -> True).
        return any(payload.startswith(prefix) for prefix in self.prefixes)